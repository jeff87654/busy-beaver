(** ** The digit family *)

Fixpoint lft (ds : list nat) : side :=
  match ds with
  | [] => const 0
  | d :: t => [1;0]^^(S (3 * d)) *> 1 >> lft t
  end.

(** Kc ds a b = 0^inf 1 (01)^(3 d_n+1) 1 ... 1 (01)^(3 d_1+1) 1 (01)^(3a+1) 1 (01)^(3b+1) 1 (01)^2 G> 0^inf
    (ds nearest-first: d_1 is the digit next to the counters) *)
Definition Kc (ds : list nat) (a b : nat) : Q * tape :=
  ([1;0]^^(2) *> 1 >> [1;0]^^(S (3 * b)) *> 1 >> [1;0]^^(S (3 * a)) *> 1 >> lft ds) {{G}}> const 0.

Lemma lft_cons : forall d t, lft (d :: t) = [1;0]^^(S (3 * d)) *> 1 >> lft t.
Proof. reflexivity. Qed.

Lemma lft_zeros : forall k t, lft (repeat O k ++ t) = [1;0;1]^^k *> lft t.
Proof. induction k; intros. - reflexivity. - simpl. rewrite IHk. reflexivity. Qed.

Lemma lft_blank : forall k, lft (repeat O k) = [1;0;1]^^k *> const 0.
Proof. intros. rewrite <- (app_nil_r (repeat O k)), lft_zeros. reflexivity. Qed.

