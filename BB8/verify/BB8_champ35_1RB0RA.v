(** Lexicographic order on lists of the same length (head = most significant). *)
Inductive lex : list nat -> list nat -> Prop :=
  | lex_hd : forall a b l l', a < b -> length l = length l' -> lex (a :: l) (b :: l')
  | lex_tl : forall a l l', lex l l' -> lex (a :: l) (a :: l').

Lemma lex_len : forall l l', lex l l' -> length l = length l'.
Proof. intros l l' H. induction H; simpl; f_equal; assumption. Qed.

Lemma lex_acc : forall n ds, length ds = n -> Acc lex ds.
Proof.
  induction n; intros ds Hl.
  - destruct ds; [| simpl in Hl; discriminate].
    constructor. intros y Hy. inversion Hy.
  - destruct ds as [| d r]; [simpl in Hl; discriminate |].
    simpl in Hl. injection Hl as Hl.
    revert r Hl.
    induction d as [d IHd] using lt_wf_ind. intros r Hl.
    assert (Hr : Acc lex r) by (apply IHn; exact Hl).
    revert Hl. induction Hr as [r _ IHr]. intros Hl.
    constructor. intros y Hy. inversion Hy; subst.
    + apply IHd; [assumption |]. lia.
    + apply IHr; [assumption |]. pose proof (lex_len _ _ H1). lia.
Qed.

Definition ltds (x y : list nat) : Prop := lex (rev x) (rev y).

Lemma ltds_acc : forall ds, Acc ltds ds.
Proof.
  intros ds. apply (Acc_inverse_image _ _ lex (@rev nat)).
  eapply lex_acc. reflexivity.
Qed.

Lemma lex_pre : forall p l l', lex l l' -> lex (p ++ l) (p ++ l').
Proof. induction p; intros; simpl; [assumption | apply lex_tl; apply IHp; assumption]. Qed.

Lemma rev_rep : forall k, rev (repeat O k) = repeat O k.
Proof.
  induction k; simpl; [reflexivity |].
  rewrite IHk. clear IHk. induction k; simpl; [reflexivity | rewrite IHk; reflexivity].
Qed.

Lemma len_rep : forall k, length (repeat O k) = k.
Proof. induction k; simpl; [reflexivity | f_equal; assumption]. Qed.

Lemma ltds_R2 : forall y t, ltds (y :: t) (S y :: t).
Proof.
  intros. unfold ltds. simpl.
  apply lex_pre. apply lex_hd; [lia | reflexivity].
Qed.

Lemma ltds_R3 : forall M y t x,
  ltds (repeat O M ++ x :: y :: t) (repeat O (S M) ++ S y :: t).
Proof.
  intros. unfold ltds.
  assert (E1 : rev (repeat O M ++ x :: y :: t) = rev t ++ y :: x :: repeat O M).
  { rewrite rev_app_distr, rev_rep. cbn [rev]. rewrite <- !app_assoc. reflexivity. }
  assert (E2 : rev (repeat O (S M) ++ S y :: t) = rev t ++ S y :: repeat O (S M)).
  { rewrite rev_app_distr, rev_rep. cbn [rev]. rewrite <- app_assoc. reflexivity. }
  rewrite E1, E2.
  apply lex_pre. apply lex_hd; [lia |]. simpl. rewrite len_rep. reflexivity.
Qed.

Lemma decomp : forall ds,
  (exists k, ds = repeat O k) \/ (exists k y t, ds = repeat O k ++ S y :: t).
Proof.
  induction ds as [| d r IH].
  - left. exists O. reflexivity.
  - destruct d.
    + destruct IH as [[k Hk] | [k [y [t Hk]]]].
      * left. exists (S k). simpl. rewrite Hk. reflexivity.
      * right. exists (S k), y, t. simpl. rewrite Hk. reflexivity.
    + right. exists O, d, r. reflexivity.
Qed.

(** Every nonempty list with a = 0 leads to a halt. *)
Theorem all_halt : forall ds, ds <> [] -> forall b,
  exists c, Kc ds O b -->* c /\ halted tm c.
Proof.
  intros ds. induction (ltds_acc ds) as [ds _ IH]. intros Hne b.
  destruct (decomp ds) as [[k Hk] | [k [y [t Hk]]]].
  - destruct k as [| M]; [subst; simpl in Hne; congruence |].
    subst. apply R4.
  - destruct k as [| M].
    + subst. simpl.
      destruct (IH (y :: t) (ltds_R2 y t) ltac:(discriminate) (dbl (2 * b + 2) O)) as [c [H1 H2]].
      exists c. split; [| exact H2].
      eapply evstep_trans; [apply progress_evstep, R2 |].
      eapply evstep_trans; [apply R1ITER |].
      exact H1.
    + subst.
      destruct (IH (repeat O M ++ (2 * b + 2) :: y :: t) (ltds_R3 M y t (2 * b + 2))
                   ltac:(destruct M; simpl; discriminate) O) as [c [H1 H2]].
      exists c. split; [| exact H2].
      eapply evstep_trans; [apply progress_evstep, R3 |].
      exact H1.
Qed.

(** ** The run from the blank tape *)

Lemma init_reach : c0 -->* Kc (repeat O 34 ++ [2]) O O.
Proof.
  unfold c0, Kc.
  do 6397 step.
  apply evstep_refl'. reflexivity.
Qed.

Theorem halt : halts tm c0.
Proof.
  destruct (all_halt (repeat O 34 ++ [2]) ltac:(discriminate) O) as [c [H1 H2]].
  assert (Hrun : c0 -->* c) by (follow init_reach; exact H1).
  destruct (with_counter Hrun) as [n Hn].
  eapply halts_multistep; [| exact Hn].
  apply halted_halts. exact H2.
Qed.

