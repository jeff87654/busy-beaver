#!/usr/bin/env python3
"""Generate verify/BB44_start.v: the chunked step-by-step proof of the start.

The blank tape reaches B(2, 6, 0) 0^inf in 98 steps for the BB(4,4) champion
0LB3LB1RZ2RA_1LD3RB1LC2RA_3RB1LB3LC2RC_0RD2RC2LB0RA.

The run is cut into chunks of 10 steps; each chunk is discharged by busycoq's
[execute] tactic.  Chunking is not cosmetic: [execute] re-normalises the whole
accumulated proof term at every step, so one monolithic 98-step [execute] is
O(n^3) in rewriting, while the chunked version is a few seconds.
"""
import sys, os

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from tm_lib import parse_machine

OURS = '0LB3LB1RZ2RA_1LD3RB1LC2RA_3RB1LB3LC2RC_0RD2RC2LB0RA'
ALPHA = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ'
SYM = {0: 'S0', 1: 'S1', 2: 'S2', 3: 'S3'}

CHUNK = 10
TOTAL = 98


class Tape:
    __slots__ = ('cells', 'p', 'state')

    def __init__(self):
        self.cells = {}
        self.p = 0
        self.state = 'A'

    def read(self):
        return self.cells.get(self.p, 0)

    def write(self, s):
        if s == 0:
            self.cells.pop(self.p, None)
        else:
            self.cells[self.p] = s

    def span(self):
        if not self.cells:
            return 0, 0
        return min(self.cells), max(self.cells)

    def step(self, m):
        i = ALPHA.index(self.state)
        cur = self.read()
        t = m.table[(i, cur)]
        if t is None or t[2] is None:
            return False
        w, d, q = t
        self.write(w)
        self.p += 1 if d == 'R' else -1
        self.state = ALPHA[q]
        return True


def side(t, right):
    """Nonzero symbols of one side, nearest-first.

    Fails loudly if the nonzero cells are not contiguous with the head: the
    generated Coq term [xs *> const 0] would then be a lie.
    """
    if right:
        idx = range(t.p + 1, t.p + 1 + 4096)
    else:
        idx = range(t.p - 1, t.p - 1 - 4096, -1)
    out = []
    seen_zero = False
    for i in idx:
        v = t.cells.get(i, 0)
        if v == 0:
            seen_zero = True
            continue
        if seen_zero:
            raise SystemExit('gap in the %s stream' %
                             ('right' if right else 'left'))
        out.append(v)
    return out


def coq_list(xs):
    if not xs:
        return 'Streams.const S0'
    body = ';'.join(SYM[x] for x in xs)
    return '[%s] *> Streams.const S0' % body


def coq_cfg(t):
    left = side(t, False)
    right = side(t, True)
    return '(%s, (%s, %s, %s))' % (t.state, coq_list(left), SYM[t.read()],
                                   coq_list(right))


def main():
    out = os.path.join(HERE, '..', 'verify', 'BB44_start.v')
    m = parse_machine(OURS)
    t = Tape()
    cfgs = [coq_cfg(t)]
    for n in range(TOTAL):
        if not t.step(m):
            raise SystemExit('machine halted early at step %d' % n)
        if (n + 1) % CHUNK == 0 or n + 1 == TOTAL:
            cfgs.append(coq_cfg(t))

    L = []
    L.append('(** * The %d-step start of the BB(4,4) champion, proved step by step.' % TOTAL)
    L.append('')
    L.append('    This file is GENERATED by tools/gen_start.py; do not edit by hand.')
    L.append('')
    L.append('    The blank tape reaches B(2, 6, 0) 0^inf in %d steps.  The run is' % TOTAL)
    L.append('    cut into chunks of %d steps; each chunk is discharged by busycoq\'s' % CHUNK)
    L.append('    [execute] tactic.  Chunking is not cosmetic: [execute] re-normalises')
    L.append('    the whole accumulated proof term at every step, so one monolithic')
    L.append('    [%d-step [execute] needs O(n^3) rewriting, while the chunked' % TOTAL)
    L.append('    version is a few seconds.  The intermediate configurations below are')
    L.append('    produced by tools/sim.py; Coq re-derives each of them from scratch. *)')
    L.append('')
    L.append('From TM44 Require Import Individual44 BB44_rules.')
    L.append('From Coq Require Import Lia PeanoNat List.')
    L.append('Import ListNotations.')
    L.append('Set Default Goal Selector "!".')
    L.append('')
    for i, c in enumerate(cfgs):
        L.append('Definition cfg_%d : Q * tape := %s.' % (i * CHUNK if i < len(cfgs) - 1 else TOTAL, c))
    L.append('')
    nchunks = len(cfgs) - 1
    for i in range(nchunks):
        a = i * CHUNK
        b = (i + 1) * CHUNK if i + 1 < nchunks else TOTAL
        L.append('Lemma chunk_%d : cfg_%d -->* cfg_%d.' % (i, a, b))
        L.append('Proof. unfold cfg_%d, cfg_%d. execute. Qed.' % (a, b))
        L.append('')
    L.append('Lemma start_raw : c0 -->* cfg_%d.' % TOTAL)
    L.append('Proof.')
    L.append('  unfold c0, tape0, cfg_%d.' % TOTAL)
    for i in range(nchunks):
        L.append('  follow (chunk_%d).' % i)
    L.append('  finish.')
    L.append('Qed.')
    L.append('')
    L.append('(** The configuration reached after %d steps is exactly Ligocki\'s' % TOTAL)
    L.append('    [B(2, 6, 0) 0^inf], i.e. [Bcfg 2 6 0 (const 0)]. *)')
    L.append('Lemma cfg_%d_is_B : cfg_%d = Bcfg 2 6 0 (const 0).' % (TOTAL, TOTAL))
    L.append('Proof. reflexivity. Qed.')
    L.append('')

    with open(out, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('\n'.join(L))
    print('wrote %s (%d chunks, %d configs)' % (os.path.abspath(out), nchunks, len(cfgs)))


if __name__ == '__main__':
    main()
