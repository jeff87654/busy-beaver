Ltac so_tac :=
  repeat match goal with
  | H : side_ones ?l _ |- side_ones ?l _ => first [exact H | eapply so_le; [exact H | lia]]
  | |- side_ones (Cons _ _) _ => apply so_cons
  | |- side_ones (lfr _ _) _ => apply so_lfr
  | |- side_ones (Str_app _ _) _ => apply so_app
  | |- side_ones (const _) _ => apply so_const
  end.

