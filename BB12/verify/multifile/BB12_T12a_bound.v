Definition step (s : nat * nat) : nat * nat :=
  let n := fst s in
  let g := snd s in
  let n2 := n + 2 * g - 6 in
  let n4 := n2 + 2 * arrow (S n2) 2 (arrow n 2 5 - 1) - 4 in
