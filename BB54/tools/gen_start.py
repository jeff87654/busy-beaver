#!/usr/bin/env python3
"""Generate BB54/verify/BB54_start.v: the first steps of the BB(5,4) run.

The blank tape reaches the Ligocki configuration B(2, 1, 0) (that is
0^inf 3 2 2 A> 1 0^inf) after 9 steps.  The run is cut into chunks; each
chunk is discharged by busycoq's [execute] tactic.
"""

import io
import os
import sys

sys.path.insert(0, ".")
from sim import Machine

CHUNK = 5

HEADER = '''(** * The 9-step start of the BB(5,4) champion, proved step by step.

    This file is GENERATED by tools/gen_start.py; do not edit by hand.

    The blank tape reaches B(2, 1, 0) 0^inf in 9 steps, i.e. the machine is
    in state A, with two twos and one three to its left, and with one 1
    under the head.  The run is cut into chunks of %d steps; each chunk is
    discharged by busycoq's [execute] tactic. *)

From TM54 Require Import Individual54 BB54_rules.
From Coq Require Import Lia PeanoNat List.
Import ListNotations.
Set Default Goal Selector "!".
'''


def sym(s):
    return "S%d" % s


def stream(cells):
    """The busycoq term for a (nearest-first) list of cells followed by blanks."""
    if not cells:
        return "Streams.const S0"
    lst = "[" + ";".join(sym(c) for c in cells) + "]"
    return lst + " *> Streams.const S0"


def run(machine, steps):
    tape = {}
    head = 0
    state = 0
    out = [(state, [], tape.get(head, 0), [])]
    for _ in range(steps):
        sym_ = tape.get(head, 0)
        r = machine.step(state, sym_)
        if r is None:
            raise SystemExit("machine halted early")
        nq, w, mv = r
        tape[head] = w
        head += 1 if mv == "R" else -1
        state = nq
        out.append((state, left_cells(tape, head), tape.get(head, 0),
                    right_cells(tape, head)))
    return out


def left_cells(tape, head):
    out = []
    j = head - 1
    while j in tape and tape[j] != 0:
        out.append(tape[j])
        j -= 1
    return out


def right_cells(tape, head):
    """The cells strictly to the right of the head, nearest first."""
    out = []
    j = head + 1
    while j in tape and tape[j] != 0:
        out.append(tape[j])
        j += 1
    return out


def cfg_term(entry):
    state, left, s, right = entry
    return "(%s, (%s, %s, %s))" % (chr(65 + state), stream(left), sym(s),
                                   stream(right))


def main():
    machine = Machine(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "bb54.txt")).read().strip())
    steps = 9
    entries = run(machine, steps)
    out = io.open("../verify/BB54_start.v", "w", encoding="utf-8")
    out.write(HEADER % CHUNK)
    for i, e in enumerate(entries):
        out.write("Definition cfg_%d : Q * tape := %s.\n" % (i, cfg_term(e)))
    out.write("\n")
    for i in range(0, steps, CHUNK):
        j = min(i + CHUNK, steps)
        out.write("Lemma chunk_%d : cfg_%d -->* cfg_%d.\n"
                  % (i, i, j))
        out.write("Proof. unfold cfg_%d, cfg_%d. execute. Qed.\n\n" % (i, j))
    out.write("(** The whole start. *)\n")
    out.write("Lemma start_raw : c0 -->* cfg_%d.\n" % steps)
    out.write("Proof.\n")
    out.write("  eapply evstep_trans; [apply chunk_0 |].\n")
    out.write("  apply chunk_%d.\n" % (steps - steps % CHUNK))
    out.write("Qed.\n")
    out.close()
    print("wrote ../verify/BB54_start.v")


if __name__ == '__main__':
    main()
