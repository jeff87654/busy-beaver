#!/usr/bin/env python3
"""Reproduce the original PA238 literal table; never modify the source machine.

Run from any working directory:
    python3 -I PA/m238/tools/gen_table.py
    python3 -I PA/m238/tools/gen_table.py --check

This is original PA238 code. The source is the pinned machine from
/Users/mira/work/mm0-bb at 6f7f0c2f97703839e56a705bbf5da5a0e5c132cf.
The generator has no third-party runtime dependencies and does not execute
external tools. Only the designated Coq output is written, after all checks.
"""

import argparse
import hashlib
from pathlib import Path
import re
import sys


STATE_COUNT = 238
SOURCE_SHA256 = "ffe370842d70bae96688ad5e290073edffe0bb213cf12fe562a75a74bec966de"
TRANSITION = re.compile(r"(0|[1-9][0-9]*) ([01]) ([01]) ([LR]) (0|[1-9][0-9]*)")
ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "machine" / "pa_238.tm"
OUTPUT = ROOT / "coq" / "tm" / "Table238.v"


def read_transitions(data):
    """Check bytes, syntax, uniqueness, totality, and the destination bound."""
    actual_hash = hashlib.sha256(data).hexdigest()
    if actual_hash != SOURCE_SHA256:
        raise ValueError(f"source SHA256 {actual_hash} differs from pinned {SOURCE_SHA256}")
    lines = data.decode("ascii").splitlines()
    if not lines or lines[0] != "#! start 0":
        raise ValueError("expected the literal initial-state header '#! start 0'")
    transitions = {}
    for line_number, line in enumerate(lines[1:], 2):
        match = TRANSITION.fullmatch(line)
        if match is None:
            raise ValueError(f"line {line_number}: invalid transition syntax")
        q, symbol, written, direction, destination = match.groups()
        key = (int(q), int(symbol))
        if key in transitions:
            raise ValueError(f"line {line_number}: duplicate state/symbol {key}")
        destination = int(destination)
        if not 0 <= destination <= STATE_COUNT:
            raise ValueError(f"line {line_number}: destination {destination} is out of range")
        transitions[key] = (written == "1", direction, destination)
    expected_keys = {(q, s) for q in range(STATE_COUNT) for s in (0, 1)}
    if set(transitions) != expected_keys:
        missing = sorted(expected_keys - set(transitions))
        extra = sorted(set(transitions) - expected_keys)
        raise ValueError(f"state/symbol domain mismatch: missing={missing}, extra={extra}")
    return transitions


def render(transitions):
    """Order rows by numeric state and columns by read symbol 0, then 1."""
    lines = [
        "(** * The original PA238 machine's exact transition table.",
        "",
        "    Generated by [PA/m238/tools/gen_table.py] from [machine/pa_238.tm].",
        f"    Source SHA256: {SOURCE_SHA256}.",
        "    Source repository pin: 6f7f0c2f97703839e56a705bbf5da5a0e5c132cf.",
        "    Each row contains the write, direction, destination triple for read 0",
        "    followed by that triple for read 1. Rows retain the original numeric",
        "    state names. State 238 is terminal and has no row.",
        "",
        "    This PA238 addition is independently authored; BusyCoq's [dir] type",
        "    is imported from the licensed semantics. No m254 proof is copied. *)",
        "",
        "From Coq Require Import Lists.List.",
        "From BusyCoq Require Import TM.",
        "Import ListNotations.",
        "",
        "Definition terminal238 : nat := 238.",
        "",
        "Definition table238 : list (bool * dir * nat * bool * dir * nat) :=",
        "  [",
    ]
    for q in range(STATE_COUNT):
        triples = []
        for symbol in (0, 1):
            written, direction, destination = transitions[q, symbol]
            triples.append(f"{'true' if written else 'false'}, {direction}, {destination}")
        separator = ";" if q + 1 < STATE_COUNT else ""
        lines.append(f"    ({', '.join(triples)}){separator}  (* state {q} *)")
    lines.extend([
        "  ].",
        "",
        "(** Numeric transition function: [true] selects the read-1 column. *)",
        "Definition tmn238 (q : nat) (symbol : bool) : option (bool * dir * nat) :=",
        "  match nth_error table238 q with",
        "  | Some (w0, d0, n0, w1, d1, n1) =>",
        "      if symbol then Some (w1, d1, n1) else Some (w0, d0, n0)",
        "  | None => None",
        "  end.",
        "",
    ])
    return "\n".join(lines).encode("ascii")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check exact output bytes without writing")
    args = parser.parse_args()
    try:
        transitions = read_transitions(SOURCE.read_bytes())
        output = render(transitions)
        if args.check:
            if not OUTPUT.is_file() or OUTPUT.read_bytes() != output:
                raise ValueError(f"{OUTPUT}: generated output differs; run without --check to reproduce")
        else:
            OUTPUT.parent.mkdir(parents=True, exist_ok=True)
            OUTPUT.write_bytes(output)
    except (OSError, UnicodeError, ValueError) as error:
        print(f"gen_table: {error}", file=sys.stderr)
        return 1
    action = "checked" if args.check else "wrote"
    print(f"{action} {OUTPUT}: {STATE_COUNT} rows, {len(transitions)} transitions, source SHA256 {SOURCE_SHA256}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
