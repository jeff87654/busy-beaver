(** ** The depth scanner: C goes one level deeper, O one level back *)

Lemma dq_C : forall i l r, i < E -> ls l [pC] <{{dq i}} r -->+ l <{{dq (S i)}} rs [pC] r.
Proof. intros i l r Hi. unfold E in Hi. do 5 (destruct i as [|i]; [simpl; execute|]). lia. Qed.

Lemma dq_O : forall i l r, S i < E -> ls l [pO] <{{dq (S i)}} r -->+ l <{{dq i}} rs [pO] r.
Proof. intros i l r Hi. unfold E in Hi. do 4 (destruct i as [|i]; [simpl; execute|]). lia. Qed.

