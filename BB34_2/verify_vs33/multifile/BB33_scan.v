(** ** Words *)

Definition isOC (p : pr) : Prop := p = pO \/ p = pC.
Definition OC (w : list pr) : Prop := Forall isOC w.
Definition OCX (w : list pr) : Prop := Forall (fun p => p <> pZ) w.

(** The bracket word of a tree, of a list of trees, and of a spine (rightmost path, open). *)
Fixpoint enc (t : tree) : list pr :=
  match t with node cs => [pO] ++ flat_map enc cs ++ [pC] end.
Definition encL (cs : list tree) : list pr := flat_map enc cs.
Definition wsp (sp : list (list tree)) : list pr := flat_map (fun L => encL L ++ [pO]) sp.

Lemma enc_node : forall cs, enc (node cs) = [pO] ++ encL cs ++ [pC].
Proof. reflexivity. Qed.

Lemma encL_app : forall a b, encL (a ++ b) = encL a ++ encL b.
Proof. intros. apply flat_map_app. Qed.

Lemma encL_single : forall t, encL [t] = enc t.
Proof. intros. unfold encL. simpl. apply app_nil_r. Qed.

Lemma encL_repeat : forall t n, encL (repeat t n) = (enc t)^^n.
Proof. intros t n. induction n as [|n IH]; [reflexivity|]. cbn [repeat lpow]. unfold encL in *. simpl. rewrite IH. reflexivity. Qed.

Lemma wsp_app : forall a b, wsp (a ++ b) = wsp a ++ wsp b.
Proof. intros. apply flat_map_app. Qed.

Lemma wsp_single : forall L, wsp [L] = encL L ++ [pO].
Proof. intros. unfold wsp. simpl. apply app_nil_r. Qed.

Lemma repeat_snoc : forall {A} (x : A) n, repeat x (S n) = repeat x n ++ [x].
Proof. induction n; simpl; [reflexivity | rewrite <- IHn; reflexivity]. Qed.

(** The word of [plug sp X]: the open spine, X, then one close bracket per spine level. *)
Lemma enc_plug : forall sp X, encL (plug sp X) = wsp sp ++ encL X ++ repeat pC (length sp).
Proof.
  induction sp as [|L sp IH]; intros X; [simpl; rewrite app_nil_r; reflexivity|].
  cbn [plug length]. rewrite encL_app, encL_single, enc_node, IH, repeat_snoc.
  change (wsp (L :: sp)) with ((encL L ++ [pO]) ++ wsp sp). rewrite <- !app_assoc. reflexivity.
Qed.

