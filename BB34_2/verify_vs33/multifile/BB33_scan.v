(** ** S9: depth scans over trees

    [dq i] scans a tree of height < h leftwards and returns to [dq i] when i + h < E (the deepest
    level visited is i + height + 1 <= E - 1). *)

Lemma dscan : forall h cs i l r, Forall (hb h) cs -> i + h < E ->
  ls l (encL cs) <{{dq i}} r -->* l <{{dq i}} rs (encL cs) r.
Proof.
  induction h as [|h IHh]; intros cs i l r Hcs Hi.
  - destruct cs as [|t cs]; [apply evstep_refl|]. inversion Hcs as [|? ? Ht _]. destruct Ht.
  - revert r Hcs. induction cs as [|t cs IHcs] using rev_ind; intros r Hcs; [apply evstep_refl|].
    apply Forall_app in Hcs as [Hcs Ht]. inversion Ht as [|? ? Ht' _]; subst.
    destruct t as [ds]. simpl in Ht'.
    rewrite encL_app, encL_single, enc_node, !ls_app, !rs_app.
    eapply evstep_trans; [apply progress_evstep, dq_C; lia|].
    eapply evstep_trans; [apply IHh; [exact Ht' | lia]|].
    eapply evstep_trans; [apply progress_evstep, dq_O; lia|].
    apply IHcs; exact Hcs.
Qed.

(** Same scan with i + h <= E: either it returns, or the escape fires inside (the head is then
    in state Y somewhere inside the scanned word, with only O/C to its left in the word). *)
Lemma dscan_esc : forall h cs i l r, Forall (hb h) cs -> i + h <= E -> i < E ->
  (ls l (encL cs) <{{dq i}} r -->* l <{{dq i}} rs (encL cs) r) \/
  (exists u v, encL cs = u ++ v /\ OC u /\ ls l (encL cs) <{{dq i}} r -->+ ls l u <{{rY}} rs v r).
Proof.
  induction h as [|h IHh]; intros cs i l r Hcs Hi Hi'.
  - left. destruct cs as [|t cs]; [apply evstep_refl|]. inversion Hcs as [|? ? Ht _]. destruct Ht.
  - revert r Hcs. induction cs as [|t cs IHcs] using rev_ind; intros r Hcs; [left; apply evstep_refl|].
    apply Forall_app in Hcs as [Hcs Ht]. inversion Ht as [|? ? Ht' _]; subst.
    destruct t as [ds]. simpl in Ht'.
    rewrite encL_app, encL_single, enc_node, !ls_app, !rs_app.
    set (L1 := ls l (encL cs)).
    destruct (Nat.eq_dec (S i) E) as [HE|HE].
    + (* the subtree is a leaf whose close takes the scan to depth E: escape *)
      assert (h = 0%nat) by lia. subst h.
      destruct ds as [|d ds]; [|inversion Ht' as [|? ? Hd _]; destruct Hd].
      right. exists (encL cs), ([pO] ++ encL [] ++ [pC]). split; [reflexivity|]. split; [oc|].
      eapply progress_trans; [apply dq_C; lia|]. rewrite HE.
      change (encL []) with (@nil pr). cbn [ls rs].
      eapply progress_evstep_trans; [apply esc_O|]. unfold L1. fin.
    + destruct (IHh ds (S i) (ls L1 [pO]) (rs [pC] r) Ht' ltac:(lia) ltac:(lia)) as [Hn | (u & v & Huv & Hu & Hesc)].
      * assert (Hstep : ls (ls (ls L1 [pO]) (encL ds)) [pC] <{{dq i}} r -->+
                        L1 <{{dq i}} rs [pO] (rs (encL ds) (rs [pC] r))).
        { eapply progress_trans; [apply dq_C; lia|]. eapply evstep_progress_trans; [exact Hn|]. apply dq_O. lia. }
        destruct (IHcs (rs [pO] (rs (encL ds) (rs [pC] r))) Hcs) as [Hn2 | (u & v & Huv & Hu & Hesc)].
        -- left. eapply evstep_trans; [apply progress_evstep, Hstep|]. exact Hn2.
        -- right. exists u, (v ++ [pO] ++ encL ds ++ [pC]).
           split; [rewrite Huv; rewrite <- !app_assoc; reflexivity|]. split; [exact Hu|].
           eapply progress_trans; [exact Hstep|]. eapply progress_evstep_trans; [exact Hesc|]. fin.
      * right. exists (encL cs ++ [pO] ++ u), (v ++ [pC]).
        split; [rewrite Huv; rewrite <- !app_assoc; reflexivity|]. split; [oc|].
        eapply progress_trans; [apply dq_C; lia|]. eapply progress_evstep_trans; [exact Hesc|].
        unfold L1. fin.
Qed.

