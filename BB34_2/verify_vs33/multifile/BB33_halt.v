(** The rightmost path of the initial hydra: level i lists the children of the i-th node on the
    path that lie left of the path. *)
Definition sp0 : list (list tree) := [[]; []; []; []; [leaf]; []; [leaf; leaf]].
Definition hs0 : list tree := plug sp0 [].
Definition w0 : list pr := wsp sp0 ++ [pX].

(** TM steps 0..288 (literal execution). *)
Lemma init : c0 -->* Cf 1 w0.
Proof. unfold Cf, K, w0, sp0. simpl. execute. Qed.

Lemma hs0_rep : HRep hs0 w0.
Proof. apply (HR_sp' sp0 0); [discriminate | reflexivity]. Qed.

Lemma hs0_hb : Forall (hb E) hs0.
Proof. unfold hs0, sp0, E. repeat (cbn [hb plug app]; constructor). Qed.

(** o(hs0) = omega^omega^omega^omega^omega^omega^3 *)
Lemma x0_eq : olist hs0 = powtower 6 (ofin 3).
Proof. vm_compute. reflexivity. Qed.

Lemma P_init : Pg (olist hs0) 4.
Proof.
  exists 1%nat, hs0, w0. split; [reflexivity|]. split; [reflexivity|].
  split; [apply hs0_hb|]. split; [apply hs0_rep | apply init].
Qed.

(** The run halts, with N ones on the tape and H_(o(hs0))(4) <= N + 2. *)
Theorem hardy_bound : exists c N, c0 -->* c /\ halted tm c /\ ones c N /\ HH (olist hs0) 4 <= N + 2.
Proof. exact (game (olist hs0) 4 (nf_olist hs0) ltac:(lia) P_init). Qed.

Theorem halt : halts tm c0.
Proof.
  destruct hardy_bound as (c & N & H1 & H2 & _).
  apply halted_evstep_halts with (c' := c); assumption.
Qed.

