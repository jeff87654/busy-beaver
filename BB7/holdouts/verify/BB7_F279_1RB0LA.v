Lemma r_end1 : forall j, (const 0) <{{A}} (0 >> 0 >> [1;1]^^j *> 1 >> 1 >> 1 >> const 0) -->+ (const 0) <{{A}} (0 >> 0 >> 1 >> 1 >> 1 >> 1 >> 0 >> [1;1;0]^^j *> 1 >> 1 >> 1 >> 1 >> const 0).
Proof.
  intros.
  destruct j as [| j8].
  - simpl. rewrite ?zc.
    eapply progress_evstep_trans; [apply r_end1_st1 |].
    finish_norm.
  - idtac.
    eapply progress_evstep_trans; [apply r_end1_st2 |].
    follow (r_end1_loop3 j8 (const 0)).
    destruct j8 as [| j9].
    + simpl. rewrite ?zc.
      follow r_end1_st4.
      finish_norm.
    + idtac.
      follow r_end1_st5.
      follow (r_end1_loop6 j9 (1 >> 1 >> const 0)).
      follow r_end1_st7.
      first [finish_norm | teq].
Qed.


(** ** The borrow loop, iterated by hand (hole2: the engine cannot frame this round itself) *)

Definition Gc (z n p y : nat) (l : side) : Q * tape := (0 >> 1 >> 0 >> [1;1;0]^^p *> 1 >> const 0) <{{A}} (1 >> 1 >> 1 >> [1]^^n *> 0 >> 0 >> [0]^^z *> 1 >> [1]^^y *> 0 >> l).

Lemma r_bor_it : forall j z n p y l, Gc (z + j) (n + 2 * j) p y l -->* Gc z n (p + j) y l.
Proof.
  induction j; intros.
  - replace (z + 0) with z by lia. replace (n + 2 * 0) with n by lia. replace (p + 0) with p by lia. apply evstep_refl.
  - replace (p + S j) with (S p + j) by lia. eapply evstep_trans; [| apply (IHj z n (S p) y l)].
    apply progress_evstep.
    eapply evstep_progress_trans; [| eapply progress_evstep_trans; [apply (r_bor_r (n + 2 * j) p y (z + j) l) |]]; unfold Gc; teq.
Qed.

Lemma r_bor : forall k m y l, (const 0) <{{A}} (0 >> 0 >> 1 >> 1 >> 1 >> 1 >> [1]^^m *> [1;1]^^k *> 0 >> 0 >> [0]^^k *> 1 >> [1]^^y *> 0 >> l) -->+ (const 0) <{{A}} (0 >> 0 >> 1 >> 1 >> 1 >> 1 >> 0 >> [1;1;0]^^k *> 1 >> 1 >> 1 >> [1]^^m *> 0 >> [1]^^y *> 0 >> l).
Proof.
  intros k m y l.
  eapply progress_evstep_trans; [apply (r_bor_a k m y l) |].
  eapply evstep_trans; [| apply progress_evstep, (r_bor_c k m y l)].
  eapply evstep_trans; [| eapply evstep_trans; [apply (r_bor_it k 0 m 0 y l) |]]; unfold Gc; teq.
Qed.

(** * Part 2: generic digit-list argument (hole2, bb7_holdouts/holes/hole2_verdicts/tools/dl_generic.v.in)

    A K-configuration is [conf A ds]: accumulator [A] and digits [ds], nearest the head first.
    Three macro rules (proved at cell level above, instantiated below):
      D : conf A (S y :: t)                          -->+ conf (A + c) (y :: t)
      B : conf (s*k + h + m) (0^(S k) ++ S y :: t)    -->+ conf a1 (tdig^k ++ (m + r0) :: y :: t)
      E : conf X (0^z)                               -->+ conf A' T  (when [phi X (0^z)]; T has no zero digit)
    The only way to get stuck is a borrow with a too small accumulator.  The invariant [okz] says: a run of
    z >= 1 zero digits that ends at a nonzero digit satisfies  s*z + h <= p + s, where p is the accumulator plus the
    digits before the run (nearer the head).  It holds initially, and each rule keeps it under the stated
    arithmetic conditions on the constants; [phi] is an extra invariant (a residue condition, or True). *)

Section DL.

Variable conf : nat -> list nat -> Q * tape.
Variables c s h a1 tdig r0 amin : nat.
Variable phi : nat -> list nat -> Prop.

Hypothesis HD : forall A y t, amin <= A -> conf A (S y :: t) -->+ conf (A + c) (y :: t).
Hypothesis HB : forall k m y t, amin <= s * k + h + m ->
  conf (s * k + h + m) (repeat O (S k) ++ S y :: t) -->+ conf a1 (repeat tdig k ++ (m + r0) :: y :: t).
Hypothesis HE : forall X z, amin <= X -> phi X (repeat O z) -> exists A' T,
  conf X (repeat O z) -->+ conf A' T /\ amin <= A' /\ Forall (fun v => 0 < v) T /\ phi A' T.
Hypothesis PD : forall A y t, phi A (S y :: t) -> phi (A + c) (y :: t).
Hypothesis PB : forall k m y t, phi (s * k + h + m) (repeat O (S k) ++ S y :: t) ->
  phi a1 (repeat tdig k ++ (m + r0) :: y :: t).
Hypothesis Hc : s + 1 <= c.
Hypothesis Hh : h <= amin + c.
Hypothesis Ht : s <= tdig.
Hypothesis Ht1 : 1 <= tdig.
Hypothesis Hr : h + s + 1 <= a1 + r0.
Hypothesis Hr0 : 1 <= r0.
Hypothesis Ha1 : amin <= a1.

Fixpoint okz (p z : nat) (T : list nat) : Prop :=
  match T with
  | [] => True
  | O :: T' => okz p (S z) T'
  | S d :: T' => (z = O \/ s * z + h <= p + s) /\ okz (p + S d) O T'
  end.

Definition INV (x : nat * list nat) : Prop :=
  amin <= fst x /\ okz (fst x) 0 (snd x) /\ phi (fst x) (snd x).

Lemma okz_mono : forall T p z p', okz p z T -> p <= p' -> okz p' z T.
Proof.
  induction T as [| [| d] T IH]; simpl; intros p z p' H Hp; auto.
  - eapply IH; eauto.
  - destruct H as [H1 H2]. split; [lia |]. eapply IH; [exact H2 | lia].
Qed.

Lemma okz_zeros : forall n T p z, okz p z (repeat O n ++ T) -> okz p (z + n) T.
Proof.
  induction n; simpl; intros T p z H.
  - rewrite Nat.add_0_r. exact H.
  - rewrite Nat.add_succ_r. apply (IHn T p (S z) H).
Qed.

Lemma okz_shift : forall T p z p', okz p z T -> p + s <= p' -> h <= p' -> okz p' (S z) T.
Proof.
  induction T as [| [| d] T IH]; simpl; intros p z p' H H1 H2; auto.
  - eapply IH; eauto.
  - destruct H as [H3 H4]. split; [right; lia |]. eapply okz_mono; [exact H4 | lia].
Qed.

Lemma okz_pos : forall T p, Forall (fun v => 0 < v) T -> okz p 0 T.
Proof.
  induction T as [| d T IH]; simpl; intros p HF; auto.
  inversion HF as [| ? ? Hd HF']; subst. destruct d as [| d]; [lia |].
  split; [left; reflexivity |]. apply IH. exact HF'.
Qed.

Lemma okz_rep : forall k T p, okz (p + tdig * k) 0 T -> okz p 0 (repeat tdig k ++ T).
Proof.
  induction k; simpl; intros T p H.
  - rewrite Nat.mul_0_r, Nat.add_0_r in H. exact H.
  - destruct (Nat.le_exists_sub 1 tdig Ht1) as [t' [Et _]]. rewrite Nat.add_1_r in Et. rewrite Et. simpl.
    split; [left; reflexivity |]. rewrite <- Et. apply IHk. eapply okz_mono; [exact H | nia].
Qed.

Lemma split0 : forall T, (exists z, T = repeat O z) \/ (exists z d T', T = repeat O z ++ S d :: T').
Proof.
  induction T as [| [| d] T IH].
  - left. exists O. reflexivity.
  - destruct IH as [[z E] | [z [d [T' E]]]]; subst.
    + left. exists (S z). reflexivity.
    + right. exists (S z), d, T'. reflexivity.
  - right. exists O, d, T. reflexivity.
Qed.

Theorem step_inv : forall x, INV x -> exists x', conf (fst x) (snd x) -->+ conf (fst x') (snd x') /\ INV x'.
Proof.
  intros [A ds] [HA [HO HP]]; simpl in *.
  destruct (split0 ds) as [[z E] | [[| k] [d [T' E]]]]; subst ds.
  - (* E: all digits zero *)
    destruct (HE A z HA HP) as [A' [T [H1 [H2 [H3 H4]]]]].
    exists (A', T). split; [exact H1 |].
    unfold INV; simpl. split; [exact H2 |]. split; [apply okz_pos, H3 | exact H4].
  - (* D *)
    simpl in HO. destruct HO as [_ HO].
    exists (A + c, d :: T'). split; [apply HD; exact HA |].
    unfold INV; simpl. split; [lia |]. split; [| apply PD; exact HP].
    destruct d as [| d].
    + simpl. eapply okz_shift; [exact HO | lia | lia].
    + simpl. split; [left; reflexivity |]. eapply okz_mono; [exact HO | lia].
  - (* B *)
    pose proof HO as HO'. apply okz_zeros in HO'. simpl in HO'. destruct HO' as [Hz HO'].
    destruct Hz as [Hz | Hz]; [discriminate |].
    assert (Hle : s * k + h <= A) by lia.
    destruct (Nat.le_exists_sub (s * k + h) A Hle) as [m [Em _]].
    replace A with (s * k + h + m) in * by lia.
    exists (a1, repeat tdig k ++ (m + r0) :: d :: T'). split; [apply HB; exact HA |].
    unfold INV; simpl. split; [exact Ha1 |]. split; [| apply PB; exact HP].
    apply okz_rep. destruct (m + r0) as [| mr] eqn:Emr; [lia |]. simpl. split; [left; reflexivity |].
    destruct d as [| d].
    + simpl. eapply okz_shift; [exact HO' | nia | nia].
    + simpl. split; [left; reflexivity |]. eapply okz_mono; [exact HO' | nia].
Qed.

Theorem dl_nonhalt : forall A0 ds0, c0 -->* conf A0 ds0 -> INV (A0, ds0) -> ~ halts tm c0.
Proof.
  intros A0 ds0 H0 HI.
  apply multistep_nonhalt with (conf A0 ds0); [exact H0 |].
  apply (progress_nonhalt_cond tm (nat * list nat) (A0, ds0) (fun x => conf (fst x) (snd x)) INV).
  - intros x Hx. destruct (step_inv x Hx) as [x' [H1 H2]]. exists x'. split; assumption.
  - exact HI.
Qed.

End DL.

(** * Part 3: the V-coded configurations of this machine and the instance of Part 2 *)

Fixpoint enc (ds : list nat) : side :=
  match ds with
  | [] => const 0
  | d :: t => [1]^^d *> 0 >> enc t
  end.

(** Tape [0^z TF 0 1^A 0 1^d1 0 1^d2 ...] with the head in state A on the blank cell left of it (TF = [], z = 2). *)
Definition conf (A : nat) (ds : list nat) : Q * tape := (const 0) <{{A}} (0 >> 0 >> [1]^^A *> 0 >> enc ds).

Lemma enc_rep : forall d j L, enc (repeat d j ++ L) = ([1]^^d ++ [0])^^j *> enc L.
Proof. induction j; intros; simpl; [reflexivity |]. rewrite IHj, !Str_app_assoc. reflexivity. Qed.

Lemma enc_allzero : forall z, enc (repeat O z) = const 0.
Proof. induction z; simpl; [reflexivity | rewrite IHz; apply zc]. Qed.

Ltac tape_eq := apply evstep_refl'; unfold conf; simpl; rewrite ?enc_rep, ?enc_allzero; norm_nat; simpl; tnorm; lia_refl.

Lemma list_sum_app : forall L1 L2, list_sum (L1 ++ L2) = list_sum L1 + list_sum L2.
Proof. induction L1; intros; simpl; [reflexivity | rewrite IHL1; lia]. Qed.
Lemma list_sum_rep : forall d j, list_sum (repeat d j) = d * j.
Proof. induction j; simpl; [lia | rewrite IHj; lia]. Qed.
Lemma pos_rep : forall d j, 0 < d -> Forall (fun v => 0 < v) (repeat d j).
Proof. induction j; simpl; intros; constructor; auto. Qed.
Ltac sum_norm := repeat (rewrite ?list_sum_app, ?list_sum_rep in *; simpl list_sum in *).
Ltac pos_tac := repeat (apply Forall_app; split); try (apply pos_rep; lia); repeat (constructor; try lia).

Definition phi (A : nat) (ds : list nat) : Prop := True.

Lemma I_D : forall A y t, 4 <= A -> conf A (S y :: t) -->+ conf (A + 3) (y :: t).
Proof.
  intros A y t HA. eapply evstep_progress_trans; [| eapply progress_evstep_trans; [apply (r_dec (A - 2) y (enc t)) |]]; tape_eq.
Qed.

Lemma I_B : forall k m y t, 4 <= 2 * k + 4 + m ->
  conf (2 * k + 4 + m) (repeat O (S k) ++ S y :: t) -->+ conf 4 (repeat 2%nat k ++ (m + 3) :: y :: t).
Proof.
  intros k m y t _. eapply evstep_progress_trans; [| eapply progress_evstep_trans; [apply (r_bor k m y (enc t)) |]]; tape_eq.
Qed.

Lemma I_E : forall X z, 4 <= X -> (fun _ _ => True) X (repeat O z) -> exists A' T,
  conf X (repeat O z) -->+ conf A' T /\ 4 <= A' /\ Forall (fun v => 0 < v) T /\ (fun _ _ => True) A' T.
Proof.
  intros X z HX HP. destruct (Nat.Even_or_Odd X) as [[q Hq] | [q Hq]].
  -
    assert (Hj : exists j, X = 2 * j + 4) by (exists (q - 2); lia). destruct Hj as [j ->].
    exists ((4)%nat), (repeat 2%nat (j) ++ repeat 4%nat (1)). split; [| split; [lia | split; [pos_tac | exact I]]].
    eapply evstep_progress_trans; [| eapply progress_evstep_trans; [apply (r_end0 j) |]]; tape_eq.
  -
    assert (Hj : exists j, X = 2 * j + 3) by (exists (q - 1); lia). destruct Hj as [j ->].
    exists ((4)%nat), (repeat 2%nat (j) ++ repeat 4%nat (1)). split; [| split; [lia | split; [pos_tac | exact I]]].
    eapply evstep_progress_trans; [| eapply progress_evstep_trans; [apply (r_end1 j) |]]; tape_eq.
Qed.

Lemma init_reach : c0 -->* conf 6 [].
Proof. unfold conf. simpl. rewrite ?zc. do 61 step. apply evstep_refl. Qed.

Lemma P_D : forall A y t, (fun _ _ => True) A (S y :: t) -> (fun _ _ => True) (A + 3) (y :: t).
