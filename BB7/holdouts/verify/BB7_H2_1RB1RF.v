Proof. induction z; intros; simpl; [reflexivity | rewrite IHz; reflexivity]. Qed.

Lemma enc_ones : forall z L, enc (repeat 1%nat z ++ L) = [1;0;0]^^z *> enc L.
Proof. induction z; intros; simpl; [reflexivity | rewrite IHz; reflexivity]. Qed.

Lemma zeros_const : forall z, [0]^^z *> const 0 = const 0.
Proof. induction z; simpl; [reflexivity | rewrite IHz; apply zero_const]. Qed.

Lemma enc_allzero : forall z, enc (repeat O z) = const 0.
Proof. intros. rewrite <- (app_nil_r (repeat O z)), enc_zeros. apply zeros_const. Qed.

Lemma enc_trail : forall D, enc (D ++ [O]) = enc D.
Proof.
  induction D as [| d D IH]; simpl.
  - apply zero_const.
  - rewrite IH. reflexivity.
Qed.

(** A trailing zero digit is only blank tape. *)
Lemma conf_trail : forall f d T, conf f (d :: T ++ [O]) = conf f (d :: T).
Proof.
  intros [] d T; unfold conf;
    change (d :: T ++ [O]) with ((d :: T) ++ [O]); rewrite enc_trail; reflexivity.
Qed.

(** ** The borrow loop: each round eats one 0 on the right and pushes 110 on the left *)

Lemma pow110 : forall c l, [1;1;0]^^c *> (1 >> 1 >> 0 >> l) = 1 >> 1 >> 0 >> [1;1;0]^^c *> l.
Proof.
  intros. change (1 >> 1 >> 0 >> l) with ([1;1;0] *> l).
  rewrite <- Str_app_assoc, lpow_shift. reflexivity.
Qed.

Lemma Wloop : forall c k l R,
  (1 >> 1 >> 1 >> [1;1]^^(k + c) *> 0 >> l) {{B}}> ([0]^^c *> R) -->*
  (1 >> 1 >> 1 >> [1;1]^^k *> 0 >> [1;1;0]^^c *> l) {{B}}> R.
Proof.
  induction c; intros.
  - rewrite Nat.add_0_r. simpl. apply evstep_refl.
  - rewrite Nat.add_succ_r. simpl.
    follow (c_round (k + c) ([0]^^c *> R) l).
    follow (IHc k (1 >> 1 >> 0 >> l) R).
    apply evstep_refl'. rewrite pow110. reflexivity.
Qed.

Lemma Wloop_inf : forall c k l,
  (1 >> 1 >> 1 >> [1;1]^^(k + c) *> 0 >> l) {{B}}> (const 0) -->*
  (1 >> 1 >> 1 >> [1;1]^^k *> 0 >> [1;1;0]^^c *> l) {{B}}> (const 0).
Proof. intros. pose proof (Wloop c k l (const 0)) as H. rewrite zeros_const in H. exact H. Qed.

(** ** The macro rules *)

Lemma R_XY : forall a d T, conf FX (S (S a) :: S d :: T) -->+ conf FY (S a :: d :: T).
Proof. intros. unfold conf. simpl. apply c_XY. Qed.

Lemma R_XE4 : forall a T, conf FX (S (S (S a)) :: O :: T) -->+ conf FE4 (S a :: T).
Proof. intros. unfold conf. simpl. apply c_XE4. Qed.

Lemma R_YX : forall b d T, conf FY (b :: S d :: T) -->+ conf FX (S (S (S (S b))) :: d :: T).
Proof. intros. unfold conf. simpl. apply c_YX. Qed.

Lemma R_YE0 : forall b T, conf FY (b :: O :: T) -->+ conf FE0 (S b :: T).
Proof. intros. unfold conf. simpl. apply c_YE0. Qed.

Lemma R_D2X : forall d T, conf FD2 (S d :: T) -->+ conf FX (S (S (S O)) :: d :: T).
Proof. intros. unfold conf. simpl. apply c_D2X. Qed.

Lemma R_E4b : forall p z d T,
  conf FE4 ((p + z) :: repeat O z ++ S d :: T) -->+ conf FD2 (repeat 1%nat z ++ S (S p) :: d :: T).
Proof.
  intros. unfold conf. simpl. rewrite enc_zeros, enc_ones. simpl.
  rewrite lpow_add, Str_app_assoc.
  eapply progress_evstep_trans; [apply c_E4b_start |].
  rewrite <- (Str_app_assoc ([1;1]^^p) ([1;1]^^z)), <- lpow_add.
  follow (Wloop z p (1 >> 1 >> const 0) (1 >> 0 >> [1;0]^^d *> 0 >> enc T)).
  apply progress_evstep. apply c_E4b_end.
Qed.

Lemma R_E4e : forall m z, conf FE4 (m :: repeat O z) -->+ conf FD2 (repeat 1%nat (S (S m))).
Proof.
  intros. unfold conf. simpl. rewrite enc_allzero, zero_const.
  rewrite <- (app_nil_r (repeat 1%nat m)), enc_ones. simpl.
  eapply progress_evstep_trans; [apply c_E4e_start |].
  follow (Wloop_inf m 0 (1 >> 1 >> const 0)).
  apply progress_evstep. apply c_E4e_end.
Qed.

Lemma R_E0b : forall p z d T,
  conf FE0 (S (p + z) :: repeat O z ++ S d :: T) -->+ conf FX (S (S O) :: repeat 1%nat z ++ S (S p) :: d :: T).
Proof.
  intros. unfold conf. simpl. rewrite enc_zeros, enc_ones. simpl.
  rewrite lpow_add, Str_app_assoc.
  eapply progress_evstep_trans; [apply c_E0b_start |].
  rewrite <- (Str_app_assoc ([1;1]^^p) ([1;1]^^z)), <- lpow_add.
  follow (Wloop z p (1 >> 1 >> 0 >> 1 >> const 0) (1 >> 0 >> [1;0]^^d *> 0 >> enc T)).
  apply progress_evstep. apply c_E0b_end.
Qed.

Lemma R_E0e : forall m z, conf FE0 (S m :: repeat O z) -->+ conf FX (S (S O) :: repeat 1%nat (S (S m))).
Proof.
  intros. unfold conf. simpl. rewrite enc_allzero, zero_const.
  rewrite <- (app_nil_r (repeat 1%nat m)), enc_ones. simpl.
  apply c_E0end.
Qed.

(** ** The invariant

    [okr sc sa z T] walks the digits after d0. [z] counts the current run of zero digits; when a run of
    [z >= 1] zeros ends at a nonzero digit, it must satisfy [z + 2 <= sc]. For the leading run
    [sc] is a form-dependent bound on d0; afterwards [sc = sa] is the weighted sum of all digits
    so far. A run of zeros at the very end is never checked (it is only blank tape). *)

Fixpoint okr (sc sa z : nat) (T : list nat) : Prop :=
  match T with
  | [] => True
  | O :: T' => okr sc sa (S z) T'
  | S d :: T' => (z = O \/ z + 2 <= sc)%nat /\ okr (sa + S d) (sa + S d) O T'
  end.

Definition lead (f : form) : nat :=
  match f with FX => 1 | FY => 3 | FE4 => 2 | FD2 => 2 | FE0 => 1 end.

Definition off (f : form) : nat :=
  match f with FX => 0 | FY => 2 | FE4 => 2 | FD2 => 2 | FE0 => 1 end.

Definition base (f : form) (d0 : nat) (T : list nat) : Prop :=
  match f with
  | FX => (2 <= d0)%nat /\ match T with S _ :: _ => True | _ => (3 <= d0)%nat end
  | _ => (1 <= d0)%nat
  end.

Definition INV (f : form) (D : list nat) : Prop :=
  match D with
  | [] => False
  | d0 :: T => base f d0 T /\ okr (d0 + lead f) (off f + d0) O T
  end.

(** ** Facts about [okr] *)

Lemma okr_mono : forall T sc sa z sc' sa',
  okr sc sa z T -> (sc <= sc')%nat -> (sa <= sa')%nat -> okr sc' sa' z T.
Proof.
  induction T as [| [| d] T IH]; simpl; intros sc sa z sc' sa' H Hc Ha; auto.
  - eapply IH; eauto.
  - destruct H as [H1 H2]. split; [lia |]. eapply IH; [exact H2 | lia | lia].
Qed.

Lemma okr_shift : forall T sc sa z sc',
  okr sc sa z T -> (sc + 1 <= sc')%nat -> (3 <= sc')%nat -> okr sc' sa (S z) T.
Proof.
  induction T as [| [| d] T IH]; simpl; intros sc sa z sc' H Hc H3; auto.
  - eapply IH; eauto.
  - destruct H as [H1 H2]. split; [lia | exact H2].
Qed.

Lemma okr_unshift : forall T sc sa z sc',
  okr sc sa (S z) T -> (sc <= sc' + 1)%nat -> okr sc' sa z T.
Proof.
  induction T as [| [| d] T IH]; simpl; intros sc sa z sc' H Hc; auto.
  - eapply IH; eauto.
  - destruct H as [H1 H2]. split; [lia | exact H2].
Qed.

Lemma okr_zeros : forall z T sc sa z0,
  okr sc sa z0 (repeat O z ++ T) -> okr sc sa (z0 + z) T.
Proof.
  induction z; simpl; intros T sc sa z0 H.
  - rewrite Nat.add_0_r. exact H.
  - rewrite Nat.add_succ_r. apply (IHz T sc sa (S z0) H).
Qed.

Lemma okr_ones : forall z L sc sa,
  okr (sa + S z) (sa + S z) O L -> okr sc sa O (repeat 1%nat (S z) ++ L).
Proof.
  induction z; simpl; intros L sc sa H.
  - split; [lia |]. exact H.
  - split; [lia |]. apply IHz. replace (sa + 1 + S z)%nat with (sa + S (S z))%nat by lia. exact H.
Qed.

Lemma okr_allones : forall z sc sa, okr sc sa O (repeat 1%nat z).
Proof.
  destruct z; simpl; intros; [exact I |].
  rewrite <- (app_nil_r (repeat 1%nat z)).
  split; [lia |].
  destruct z; [simpl; exact I |]. apply okr_ones. exact I.
Qed.

Lemma split0 : forall T, (exists z, T = repeat O z) \/ (exists z d T', T = repeat O z ++ S d :: T').
Proof.
  induction T as [| [| d] T IH].
  - left. exists O. reflexivity.
  - destruct IH as [[z E] | [z [d [T' E]]]]; subst.
    + left. exists (S z). reflexivity.
    + right. exists (S z), d, T'. reflexivity.
  - right. exists O, d, T. reflexivity.
Qed.

(** [okr] after a digit that was decremented: if it became 0, the next run grows by one. *)
Lemma okr_dec : forall d T s sc sa,
  okr s s O T -> (s <= sa + d)%nat -> (d = O -> s + 1 <= sc /\ 3 <= sc)%nat ->
  okr sc sa O (d :: T).
Proof.
  intros [| d] T s sc sa H H1 H2; simpl.
  - destruct (H2 eq_refl) as [H3 H4].
    apply (okr_mono T sc s 1 sc sa); [| lia | lia].
    eapply okr_shift; [exact H | lia | exact H4].
  - split; [lia |]. eapply okr_mono; [exact H | lia | lia].
Qed.

Lemma okr_ones_gen : forall z L sc sa,
  okr (sa + z) (sa + z) O L -> (sa <= sc)%nat -> okr sc sa O (repeat 1%nat z ++ L).
Proof.
  intros [| z] L sc sa H Hs.
  - simpl. eapply okr_mono; [exact H | lia | lia].
  - apply okr_ones. exact H.
Qed.

(** ** One macro step preserves the invariant *)

Ltac dec_tac HO := eapply okr_dec; [exact HO | lia | intros; subst; lia].

Theorem step_inv : forall f D, INV f D ->
  exists f' D', conf f D -->+ conf f' D' /\ INV f' D'.
Proof.
  intros f [| d0 T]; [simpl; tauto |].
  intros [HB HO].
  destruct f; simpl in HB, HO.
  - (* X *)
    destruct HB as [H2 H3].
    destruct T as [| [| d] T'].
    + destruct d0 as [| [| [| a]]]; try lia.
      exists FE4, [S a]. split.
      * rewrite <- (conf_trail FX (S (S (S a))) []). apply R_XE4.
      * simpl. split; [lia | exact I].
    + destruct d0 as [| [| [| a]]]; try lia.
      exists FE4, (S a :: T'). split; [apply R_XE4 |].
      simpl. split; [lia |]. eapply okr_unshift; [exact HO | lia].
    + destruct d0 as [| [| a]]; try lia.
      exists FY, (S a :: d :: T'). split; [apply R_XY |].
      simpl. split; [lia |]. destruct HO as [_ HO]. dec_tac HO.
  - (* Y *)
    destruct T as [| [| d] T'].
    + exists FE0, [S d0]. split.
      * rewrite <- (conf_trail FY d0 []). apply R_YE0.
      * simpl. split; [lia | exact I].
    + exists FE0, (S d0 :: T'). split; [apply R_YE0 |].
      simpl. split; [lia |]. eapply okr_unshift; [exact HO | lia].
    + exists FX, (S (S (S (S d0))) :: d :: T'). split; [apply R_YX |].
      simpl. split; [split; [lia | destruct d; [lia | exact I]] |].
      destruct HO as [_ HO]. dec_tac HO.
  - (* E4 *)
    destruct (split0 T) as [[z E] | [z [d [T' E]]]]; subst T.
    + exists FD2, (repeat 1%nat (S (S d0))). split; [apply R_E4e |].
      simpl. repeat split; try lia; try exact I. apply okr_allones.
    + apply okr_zeros in HO. simpl in HO. destruct HO as [Hz HO].
      assert (Hle : (z <= d0)%nat) by lia.
      destruct (Nat.le_exists_sub z d0 Hle) as [p [Ep _]]. subst d0.
      exists FD2, (repeat 1%nat z ++ S (S p) :: d :: T'). split; [apply R_E4b |].
      destruct z as [| z].
      * simpl. split; [lia |]. dec_tac HO.
      * cbv [INV base lead off]. simpl repeat. simpl app. split; [lia |].
        apply okr_ones_gen; [| lia]. simpl. split; [lia |]. dec_tac HO.
  - (* D2 *)
    destruct d0 as [| d]; [lia |].
    exists FX, (S (S (S O)) :: d :: T). split; [apply R_D2X |].
    simpl. split; [split; [lia | destruct d; [lia | exact I]] |].
    apply (okr_dec d T (S (S (S d)))); [eapply okr_mono; [exact HO | lia | lia] | lia | intros; subst; lia].
  - (* E0 *)
    destruct (split0 T) as [[z E] | [z [d [T' E]]]]; subst T.
    + destruct d0 as [| m]; [lia |].
      exists FX, (S (S O) :: repeat 1%nat (S (S m))). split; [apply R_E0e |].
      simpl. repeat split; try lia; try exact I. apply okr_allones.
    + apply okr_zeros in HO. simpl in HO. destruct HO as [Hz HO].
      assert (Hle : (S z <= d0)%nat) by lia.
      destruct (Nat.le_exists_sub (S z) d0 Hle) as [p [Ep _]]. subst d0.
      replace (p + S z)%nat with (S (p + z)) in * by lia.
      exists FX, (S (S O) :: repeat 1%nat z ++ S (S p) :: d :: T'). split; [apply R_E0b |].
      cbv [INV base lead off]. split; [split; [lia | destruct z; exact I] |].
      apply okr_ones_gen; [| lia]. simpl. split; [lia |]. dec_tac HO.
Qed.

(** ** Start: the blank tape reaches D2 [1] after 19 steps *)

Lemma init_reach : c0 -->* conf FD2 [S O].
Proof.
  unfold conf. simpl. rewrite ?zero_const.
  do 19 step. apply evstep_refl.
Qed.

Theorem nonhalt : ~ halts tm c0.
Proof.
  apply multistep_nonhalt with (conf FD2 [S O]); [apply init_reach |].
  apply (progress_nonhalt_cond tm (form * list nat) (FD2, [S O])
           (fun i => conf (fst i) (snd i)) (fun i => INV (fst i) (snd i))).
  - intros [f D] H. simpl in H.
    destruct (step_inv f D H) as [f' [D' [H1 H2]]].
    exists (f', D'). simpl. split; assumption.
  - simpl. split; [lia | exact I].
Qed.
