(** * Part 2: the digit-list model, the invariant, and non-halting *)

(** ** Encoding

    A configuration is a form (the shape of the left end, where the head is) and a digit list
    [D = d0 :: T]. The tape right of the head is [enc D], where each digit [d] is the run (10)^d and
    digits are separated by one extra 0. Zero digits are adjacent separators. A trailing zero digit
    only adds blank cells, so [enc (D ++ [0])] is the same tape as [enc D]. *)

Fixpoint enc (D : list nat) : side :=
  match D with
  | [] => const 0
  | d :: D' => [1;0]^^d *> 0 >> enc D'
  end.

Inductive form := FX | FY | FE4 | FD2 | FE0.

(** The five left-end shapes:  X = 0^inf 1 C> 0 ... (the head on the 0 of the first unit),
    Y = 0^inf 1 C> 1 1 0 word,  E4 = 0^inf 1 E> 1 1 1 0 word,  D2 = 0^inf 1 D> 1 0 word,
    E0 = 0^inf 1 E> 0 1 1 0 word. *)
Definition conf (f : form) (D : list nat) : Q * tape :=
  match f with
  | FX => match D with
          | S a :: T => (1 >> const 0) {{B}}> (0 >> [1;0]^^a *> 0 >> enc T)
          | _ => c0
          end
  | FY => (1 >> const 0) {{B}}> (1 >> 1 >> 0 >> enc D)
  | FE4 => (1 >> const 0) {{D}}> (1 >> 1 >> 1 >> 0 >> enc D)
  | FD2 => (1 >> const 0) {{C}}> (1 >> 0 >> enc D)
  | FE0 => (1 >> const 0) {{D}}> (0 >> 1 >> 1 >> 0 >> enc D)
  end.

