  - intros x Hx. destruct (step_inv x Hx) as [x' [H1 H2]]. exists x'. split; assumption.
  - exact HI.
Qed.

End DL.

(** * Part 3: the V-coded configurations of this machine and the instance of Part 2 *)

Fixpoint enc (ds : list nat) : side :=
  match ds with
  | [] => const 0
  | d :: t => [1;0]^^d *> 0 >> enc t
  end.

(** Tape [... 1^d2 0 1^d1 0 1^A 0 TF 0^z] with the head in state B on the blank cell right of it (TF = [], z = 0). *)
Definition conf (A : nat) (ds : list nat) : Q * tape := ([1;0]^^A *> 0 >> enc ds) {{B}}> (const 0).

Lemma enc_rep : forall d j L, enc (repeat d j ++ L) = ([1;0]^^d ++ [0])^^j *> enc L.
Proof. induction j; intros; simpl; [reflexivity |]. rewrite IHj, !Str_app_assoc. reflexivity. Qed.

Lemma enc_allzero : forall z, enc (repeat O z) = const 0.
Proof. induction z; simpl; [reflexivity | rewrite IHz; apply zc]. Qed.

Ltac tape_eq := apply evstep_refl'; unfold conf; simpl; rewrite ?enc_rep, ?enc_allzero; norm_nat; simpl; tnorm; lia_refl2.

Lemma list_sum_app : forall L1 L2, list_sum (L1 ++ L2) = list_sum L1 + list_sum L2.
Proof. induction L1; intros; simpl; [reflexivity | rewrite IHL1; lia]. Qed.
Lemma list_sum_rep : forall d j, list_sum (repeat d j) = d * j.
Proof. induction j; simpl; [lia | rewrite IHj; lia]. Qed.
Lemma pos_rep : forall d j, 0 < d -> Forall (fun v => 0 < v) (repeat d j).
Proof. induction j; simpl; intros; constructor; auto. Qed.
Ltac sum_norm := repeat (rewrite ?list_sum_app, ?list_sum_rep in *; simpl list_sum in *).
Ltac pos_tac := repeat (apply Forall_app; split); try (apply pos_rep; lia); repeat (constructor; try lia).

Definition phi (A : nat) (ds : list nat) : Prop := True.

Lemma I_D : forall A y t, 2 <= A -> conf A (S y :: t) -->+ conf (A + 2) (y :: t).
Proof.
  intros A y t HA. assert (Hd : 1 <= A) by lia. destruct (Nat.le_exists_sub 1 A Hd) as [a [Ea _]]; subst A.
  eapply evstep_progress_trans; [| eapply progress_evstep_trans; [apply (r_dec a y (enc t)) |]]; tape_eq.
Qed.

Lemma I_B : forall k m y t, 2 <= 1 * k + 2 + m ->
  conf (1 * k + 2 + m) (repeat O (S k) ++ S y :: t) -->+ conf 2 (repeat 1%nat k ++ (m + 2) :: y :: t).
Proof.
  intros k m y t _. eapply evstep_progress_trans; [| eapply progress_evstep_trans; [apply (r_bor k m y (enc t)) |]]; tape_eq.
Qed.

Lemma I_E : forall X z, 2 <= X -> 2 <= X -> (fun _ _ => True) X (repeat O z) -> exists A' T,
  conf X (repeat O z) -->+ conf A' T /\ 2 <= A' /\ Forall (fun v => 0 < v) T /\ (fun _ _ => True) A' T /\ (T = [] -> 2 <= A').
Proof.
  intros X z HX HXa HP. assert (Hj : exists j, X = j + 2) by (exists (X - 2); lia). destruct Hj as [j ->].
  exists ((2)%nat), (repeat 1%nat (j) ++ repeat 3%nat (1)). split; [| split; [lia | split; [pos_tac | split; [exact I | intro HT; apply (f_equal (@length nat)) in HT; rewrite ?app_length, ?repeat_length in HT; simpl in HT; lia]]]].
  eapply evstep_progress_trans; [| eapply progress_evstep_trans; [apply (r_end0 j) |]]; tape_eq.
Qed.

Lemma init_reach : c0 -->* conf 4 [].
Proof. unfold conf. simpl. rewrite ?zc. do 25 step. apply evstep_refl. Qed.

Lemma P_D : forall A y t, (fun _ _ => True) A (S y :: t) -> (fun _ _ => True) (A + 2) (y :: t).
Proof. intros; exact I. Qed.
Lemma P_B : forall k m y t, (fun _ _ => True) (1 * k + 2 + m) (repeat O (S k) ++ S y :: t) ->
  (fun _ _ => True) 2 (repeat 1%nat k ++ (m + 2) :: y :: t).
Proof. intros; exact I. Qed.

Theorem nonhalt : ~ halts tm c0.
Proof.
  apply (dl_nonhalt conf 2%nat 1%nat 2%nat 2%nat 1%nat 2%nat 2%nat 2%nat (fun _ _ => True)) with (A0 := 4%nat) (ds0 := []);
    try exact I_D; try exact I_B; try exact I_E; try exact P_D; try exact P_B; try exact init_reach; try lia.
  unfold INV. simpl. split; [lia |]. split; [repeat split; lia | split; [exact I | intros [| z'] Hz; simpl in Hz; try discriminate; lia]].
Qed.
