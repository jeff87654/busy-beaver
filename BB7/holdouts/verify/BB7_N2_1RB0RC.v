(** ** The invariant *)

Definition OO (d : nat * nat) : Prop := Nat.Odd (fst d) /\ Nat.Odd (snd d).

Definition Valid (x y : nat) (U : list (nat * nat)) : Prop :=
  (Nat.Odd x /\ Nat.Odd y /\ Forall OO U) \/
  (Nat.Even x /\ Nat.Odd y /\ exists M e o, U = M ++ [(e, o)] /\ Forall OO M /\ Nat.Even e /\ Nat.Odd o).



Lemma split_ones : forall U, exists j rest, U = repeat one j ++ rest /\ (rest = [] \/ exists D V, rest = D :: V /\ D <> one).
Proof.
  induction U as [| D U IH].
  - exists 0%nat, (@nil (nat * nat)). auto.
  - destruct D as [p q].
    destruct (Nat.eq_dec p 1) as [Hp | Hp]; destruct (Nat.eq_dec q 1) as [Hq | Hq]; subst.
    + destruct IH as [j [rest [-> H]]]. exists (S j), rest. split; [reflexivity | exact H].
    + exists 0%nat, ((1%nat, q) :: U). split; [reflexivity |]. right. exists (1%nat, q), U. split; [reflexivity |].
      intro E. injection E. intros. contradiction.
    + exists 0%nat, ((p, 1%nat) :: U). split; [reflexivity |]. right. exists (p, 1%nat), U. split; [reflexivity |].
      intro E. injection E. intros. contradiction.
    + exists 0%nat, ((p, q) :: U). split; [reflexivity |]. right. exists (p, q), U. split; [reflexivity |].
      intro E. injection E. intros. contradiction.
Qed.

Lemma Forall_repeat_one : forall j, Forall OO (repeat one j).
Proof.
  induction j; simpl; constructor; auto. unfold OO, one. simpl. split; exists 0%nat; reflexivity.
Qed.

Lemma Forall_app_inv : forall (P : nat * nat -> Prop) l1 l2, Forall P (l1 ++ l2) -> Forall P l1 /\ Forall P l2.
Proof. intros. apply Forall_app in H. exact H. Qed.



Lemma odd_cases : forall n, Nat.Odd n -> n = 1%nat \/ exists k, n = (3 + k)%nat /\ Nat.Even k.
Proof.
  intros n [k ->]. destruct k as [| k].
  - left. reflexivity.
  - right. exists (2 * k)%nat. split; [lia | exists k; lia].
Qed.

Lemma even_cases : forall n, Nat.Even n -> n = 0%nat \/ exists k, n = (2 + k)%nat /\ Nat.Even k.
Proof.
  intros n [k ->]. destruct k as [| k].
  - left. reflexivity.
  - right. exists (2 * k)%nat. split; [lia | exists k; lia].
Qed.

Ltac oddp := repeat match goal with
  | H : Nat.Odd _ |- _ => destruct H
  | H : Nat.Even _ |- _ => destruct H
  end;
  match goal with
  | |- Nat.Odd _ => eexists; lia
  | |- Nat.Even _ => eexists; lia
  end.

Lemma OO_intro : forall p q, Nat.Odd p -> Nat.Odd q -> OO (p, q).
Proof. intros. split; assumption. Qed.

Lemma odd_add_even : forall a b, Nat.Even a -> Nat.Odd b -> Nat.Odd (a + b).
Proof. intros a b [i ->] [k ->]. exists (i + k)%nat. lia. Qed.
