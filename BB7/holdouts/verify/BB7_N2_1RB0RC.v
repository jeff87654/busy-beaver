(** ** Configurations (hand-written part) *)

(** A segment (01)^p (10)^q, read leftwards from its right end, in front of the side r. *)
Definition seg (p q : nat) (r : side) : side := [0;1]^^q *> [1;0]^^p *> r.

(** The segments to the left of the accumulator, nearest first, each preceded by its separator 11. *)
Fixpoint sep (U : list (nat * nat)) : side :=
  match U with
  | [] => const 0
  | (p, q) :: t => 1 >> 1 >> seg p q (sep t)
  end.

(** K-configuration: 0^inf S_1 11 S_2 11 ... 11 S_(k-1) 11 (01)^x (10)^y  A> 01 0^inf,
    with U = [S_(k-1); ...; S_1]. *)
Definition K (x y : nat) (U : list (nat * nat)) : Q * tape :=
  seg x y (sep U) {{A}}> (0 >> 1 >> const 0).

Definition one : nat * nat := (1%nat, 1%nat).
Notation U6 := ([1;1;0;1;1;0] : list Sym).   (* separator + segment (1,1), read leftwards *)
Notation T6 := ([0;1;1;0;1;1] : list Sym).   (* the unit eaten by L1 *)
Notation V6 := ([1;0;1;1;0;1] : list Sym).   (* the unit pushed by L3 *)

Definition Wsep (c n : nat) : side := 1 >> 1 >> [0;1]^^c *> 0 >> 0 >> [1;1]^^n *> const 0.
Definition Wre (n : nat) : side := 0 >> 0 >> [1;1]^^n *> const 0.
Definition Wb (c n : nat) : side := [0;1]^^c *> 0 >> 0 >> [1;1]^^n *> const 0.

Ltac fin := unfold Wsep, Wre, Wb in *; finish.

