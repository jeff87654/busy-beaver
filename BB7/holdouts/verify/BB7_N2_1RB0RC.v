Lemma step_valid : forall x y U, Valid x y U -> exists x' y' U', Valid x' y' U' /\ K x y U -->+ K x' y' U'.
Proof.
  intros x y U [[Hx [Hy HU]] | [Hx [Hy [M [e [o [HUe [HM [He Ho]]]]]]]]].
  - (* phase O *)
    destruct (odd_cases x Hx) as [Hx1 | [x' [Hx3 Hx']]]; subst x.
    + destruct (split_ones U) as [j [rest [HUj [Hr | [D [V [Hr HD]]]]]]]; subst U; subst rest.
      * (* exhaustion *)
        rewrite app_nil_r. destruct Hy as [m Hm]. replace y with (1 + 2 * m)%nat by lia. clear Hm.
        destruct j as [| i].
        -- do 3 eexists. split; [| apply R4K0].
           right. split; [exact even_0 |]. split; [exact odd_3 |].
           exists (repeat one (m + 0 + 1)), 0%nat, 1%nat. split; [reflexivity |].
           split; [apply Forall_repeat_one | split; [exact even_0 | exact odd_1]].
        -- do 3 eexists. split; [| apply R4KS].
           right. split; [exact even_0 |]. split; [exact odd_3 |].
           exists (repeat one (m + S i + 1)), 0%nat, 1%nat. split; [reflexivity |].
           split; [apply Forall_repeat_one | split; [exact even_0 | exact odd_1]].
      * apply Forall_app in HU. destruct HU as [_ HDV]. inversion HDV as [| ? ? HD' HV]. subst.
        destruct D as [p q]. destruct HD' as [Hp Hq]. simpl in Hp, Hq.
        destruct (odd_cases q Hq) as [Hq1 | [q' [Hq3 Hq']]]; subst q.
        -- destruct (odd_cases p Hp) as [Hp1 | [p' [Hp3 Hp']]]; subst p.
           ++ exfalso. apply HD. reflexivity.
           ++ do 3 eexists. split; [| apply R3K].
              left. split; [exact odd_1 |]. split; [exact odd_1 |].
              apply Forall_OO_app_cons; [apply Forall_repeat_one | | exact HV].
              split; simpl; [apply odd_1plus_even; exact Hp' | apply oddS2; exact Hy].
        -- destruct (odd_pred_even p Hp) as [p0 [Hp0 Hp0e]]. subst p.
           destruct j as [| i].
           ++ do 3 eexists. split; [| apply R2K0].
              left. split; [apply oddS2; exact Hy |]. split; [exact odd_1 |].
              constructor; [| exact HV]. split; simpl; [apply odd_1plus_even; exact Hp0e | apply odd_1plus_even; exact Hq'].
           ++ do 3 eexists. split; [| apply R2KS].
              left. split; [exact odd_1 |]. split; [exact odd_1 |].
              apply Forall_OO_app_cons; [apply Forall_repeat_one | | ].
              ** split; simpl; [apply oddS2; exact Hy | exact odd_1].
              ** constructor; [| exact HV]. split; simpl; [apply odd_1plus_even; exact Hp0e | apply odd_1plus_even; exact Hq'].
    + (* x = 3 + x' *)
      do 3 eexists. split; [| apply (R1K (1 + x') y U)].
      left. split; [apply odd_1plus_even; exact Hx' |]. split; [apply oddS2; exact Hy | exact HU].
  - (* phase E *)
    subst U.
    destruct (even_cases x Hx) as [Hx0 | [x' [Hx2 Hx']]]; subst x.
    + destruct (odd_pred_even y Hy) as [y' [Hy' Hy'e]]. subst y.
      destruct (split_ones M) as [j [rest [HMj [Hr | [D [V [Hr HD]]]]]]]; subst M; subst rest.
      * (* all middle digits are (1,1): the leftmost digit (e, o) is the donor *)
        rewrite app_nil_r.
        destruct (odd_cases o Ho) as [Ho1 | [o' [Ho3 Ho']]]; subst o.
        -- destruct (even_cases e He) as [He0 | [e' [He2 He']]]; subst e.
           ++ destruct j as [| i].
              ** do 3 eexists. split; [| apply (R8bK (1 + y'))].
                 left. split; [apply odd_2plus; apply odd_1plus_even; exact Hy'e |].
                 split; [exact odd_3 | constructor].
              ** do 3 eexists. split; [| apply R8aK].
                 right. split; [exact even_0 |]. split; [exact odd_3 |].
                 exists (repeat one i), (4 + y')%nat, 1%nat. split; [reflexivity |].
                 split; [apply Forall_repeat_one | split; [apply even_2plus, even_2plus; exact Hy'e | exact odd_1]].
           ++ destruct (even_cases e' He') as [He'0 | [e'' [He'2 He'']]]; subst e'.
              ** do 3 eexists. split; [| apply R7K2].
                 right. split; [exact even_0 |]. split; [exact odd_3 |].
                 exists (repeat one j), 0%nat, (3 + y')%nat. split; [reflexivity |].
                 split; [apply Forall_repeat_one | split; [exact even_0 |]].
                 apply odd_2plus. apply odd_1plus_even. exact Hy'e.
              ** do 3 eexists. split; [| apply (R7KL j e'' y')].
                 right. split; [exact even_0 |]. split; [exact odd_3 |].
                 exists (repeat one j), (2 + e'')%nat, (3 + y')%nat. split; [reflexivity |].
                 split; [apply Forall_repeat_one | split; [apply even_2plus; exact He'' |]].
                 apply odd_2plus. apply odd_1plus_even. exact Hy'e.
        -- destruct j as [| i].
           ++ do 3 eexists. split; [| apply (R6bK e o' (1 + y') (@nil (nat * nat)))].
              right. split; [apply even_1plus_odd; apply odd_1plus_even; exact Hy'e |]. split; [exact odd_3 |].
              exists (@nil (nat * nat)), e, (1 + o')%nat. split; [reflexivity |].
              split; [constructor | split; [exact He | apply odd_1plus_even; exact Ho']].
           ++ do 3 eexists. split; [| apply (R6aK i e o' y' (@nil (nat * nat)))].
              right. split; [exact even_0 |]. split; [exact odd_3 |].
              exists (repeat one i ++ [(3 + y', 1%nat)]), e, (1 + o')%nat. split.
              { rewrite <- app_assoc. reflexivity. }
              split; [| split; [exact He | apply odd_1plus_even; exact Ho']].
              apply Forall_app. split; [apply Forall_repeat_one |]. constructor; [| constructor].
              split; simpl; [apply odd_2plus; apply odd_1plus_even; exact Hy'e | exact odd_1].
      * (* a middle donor D *)
        apply Forall_app in HM. destruct HM as [_ HDV]. inversion HDV as [| ? ? HD' HV]. subst.
        destruct D as [p q]. destruct HD' as [Hp Hq]. simpl in Hp, Hq.
        destruct (odd_cases q Hq) as [Hq1 | [q' [Hq3 Hq']]]; subst q.
        -- destruct (odd_cases p Hp) as [Hp1 | [p' [Hp3 Hp']]]; subst p.
           ++ exfalso. apply HD. reflexivity.
           ++ destruct (V ++ [(e, o)]) as [| [a b] V'] eqn:HVe.
              ** exfalso. destruct V; discriminate.
              ** rewrite <- app_assoc. simpl. rewrite HVe.
                 do 3 eexists. split; [| apply R7K].
                 right. split; [exact even_0 |]. split; [exact odd_3 |].
                 exists (repeat one j ++ (1 + p', 3 + y')%nat :: V), e, o. split.
                 { rewrite <- app_assoc. simpl. rewrite HVe. reflexivity. }
                 split; [| split; assumption].
                 apply Forall_OO_app_cons; [apply Forall_repeat_one | | exact HV].
                 split; simpl; [apply odd_1plus_even; exact Hp' | apply odd_2plus; apply odd_1plus_even; exact Hy'e].
        -- destruct j as [| i].
           ++ rewrite <- app_assoc. simpl.
              do 3 eexists. split; [| apply (R6bK p q' (1 + y'))].
              right. split; [apply even_1plus_odd; apply odd_1plus_even; exact Hy'e |]. split; [exact odd_3 |].
              exists ((p, 1 + q')%nat :: V), e, o. split; [reflexivity |].
              split; [| split; assumption].
              constructor; [| exact HV]. split; simpl; [exact Hp | apply odd_1plus_even; exact Hq'].
           ++ rewrite <- app_assoc. simpl.
              do 3 eexists. split; [| apply (R6aK i p q' y')].
              right. split; [exact even_0 |]. split; [exact odd_3 |].
              exists (repeat one i ++ (3 + y', 1%nat) :: (p, 1 + q')%nat :: V), e, o. split.
              { rewrite <- app_assoc. reflexivity. }
              split; [| split; assumption].
              apply Forall_OO_app_cons; [apply Forall_repeat_one | |].
              ** split; simpl; [apply odd_2plus; apply odd_1plus_even; exact Hy'e | exact odd_1].
              ** constructor; [| exact HV]. split; simpl; [exact Hp | apply odd_1plus_even; exact Hq'].
    + (* x = 2 + x' *)
      do 3 eexists. split; [| apply (R1K x' y (M ++ [(e, o)]))].
      right. split; [exact Hx' |]. split; [apply oddS2; exact Hy |].
      exists M, e, o. auto.
Qed.

