Proof. intros a b [i ->] [k ->]. exists (i + k + 1)%nat. lia. Qed.

Lemma Forall_OO_app_cons : forall A d B, Forall OO A -> OO d -> Forall OO B -> Forall OO (A ++ d :: B).
Proof. intros. apply Forall_app. split; [assumption | constructor; assumption]. Qed.

