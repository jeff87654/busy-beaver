(** ** The invariant

    [okr sc sa z T] walks the digits after d0. [z] counts the current run of zero digits; when a run of
    [z >= 1] zeros ends at a nonzero digit, it must satisfy [z + 2 <= sc], where [sc = sa] is the
    prefix sum of all digits before that zero run. A run of zeros at the very end is never checked
    (it is only blank tape). *)

Fixpoint okr (sc sa z : nat) (T : list nat) : Prop :=
  match T with
  | [] => True
  | O :: T' => okr sc sa (S z) T'
  | S d :: T' => (z = O \/ z + 2 <= sc)%nat /\ okr (sa + S d) (sa + S d) O T'
  end.

Definition INV (D : list nat) : Prop :=
  match D with
  | [] => False
  | d0 :: T => (2 <= d0)%nat /\ okr d0 d0 O T
  end.

