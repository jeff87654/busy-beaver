    assert (Hle : (S (S (S k)) <= d0)%nat) by lia.
    destruct (Nat.le_exists_sub (S (S (S k))) d0 Hle) as [m [Em _]]. subst d0.
    replace (m + S (S (S k)))%nat with (S (S (S (k + m)))) in * by lia.
    exists (S (S O) :: repeat 1%nat k ++ S (S (S m)) :: d :: T'). split; [apply R_borrow |].
    unfold INV. split; [lia |].
    apply okr_ones_gen; [| lia]. simpl. split; [lia |]. dec_tac HO.
Qed.

