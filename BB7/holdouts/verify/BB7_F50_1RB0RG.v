  conf (1 * k + 1 + m) (repeat O (S k) ++ S y :: t) -->+ conf 1 (repeat 1%nat k ++ (m + 2) :: y :: t).
Proof.
  intros k m y t _. eapply evstep_progress_trans; [| eapply progress_evstep_trans; [apply (r_bor k m y (enc t)) |]]; tape_eq.
Qed.

Lemma I_E : forall X z, 1 <= X -> (fun _ _ => True) X (repeat O z) -> exists A' T,
  conf X (repeat O z) -->+ conf A' T /\ 1 <= A' /\ Forall (fun v => 0 < v) T /\ (fun _ _ => True) A' T.
Proof.
  intros X z HX HP. assert (Hj : exists j, X = j + 1) by (exists (X - 1); lia). destruct Hj as [j ->].
  exists ((1)%nat), (repeat 1%nat (j) ++ repeat 3%nat (1)). split; [| split; [lia | split; [pos_tac | exact I]]].
  eapply evstep_progress_trans; [| eapply progress_evstep_trans; [apply (r_end0 j) |]]; tape_eq.
Qed.

Lemma init_reach : c0 -->* conf 2 [].
Proof. unfold conf. simpl. rewrite ?zc. do 5 step. apply evstep_refl. Qed.

Lemma P_D : forall A y t, (fun _ _ => True) A (S y :: t) -> (fun _ _ => True) (A + 2) (y :: t).
