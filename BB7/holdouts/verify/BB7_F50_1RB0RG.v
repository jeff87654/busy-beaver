Theorem nonhalt : ~ halts tm c0.
Proof.
  apply (dl_nonhalt conf 2%nat 1%nat 1%nat 1%nat 1%nat 2%nat 1%nat (fun _ _ => True)) with (A0 := 2%nat) (ds0 := []);
    try exact I_D; try exact I_B; try exact I_E; try exact P_D; try exact P_B; try exact init_reach; try lia.
