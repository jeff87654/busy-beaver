(** * BB31: hydra-level rounds and the ordinal analysis of the game (Hardy.hardy_game).

    Generated by BB31/verify/generator/gen.py from tmpl/game.v.

    Termination and the score bound come from one well-founded argument: [Hardy.hardy_game],
    instantiated with
      P x n  :=  some configuration C(n-3, hs) is reachable from c0, with x = o(hs) and hs of
                 height <= E (o = ordinary sum in tape order, HydraOrd.olist),
      W v    :=  the machine halts from c0 with N ones and v <= N + 2.
    Each round C(m, hs) -> C(m+1, hs') satisfies (HydraOrd.chop_ord):
      successor (the rightmost head is a child of the root):  o(hs') = o(hs) - 1;
      limit:  o(hs)[m+3] <= o(hs') < o(hs),
    and HydraOrd.desc_between turns the limit case into the [1]-descent that hardy_game asks
    for.  Unsorted hydras (an extra leading leaf inside some nodes) need no special treatment. *)

From BB8 Require Import BB31_tm BB31_rules BB31_scan BB31_round Ord Hardy HydraOrd.
From Coq Require Import Lia List PeanoNat.
Import ListNotations.
Set Default Goal Selector "!".

(** ** Hydra words *)

(** [HRep hs w]: the word [w] encodes the hydra [hs] (the root's children) with the marked node M
    somewhere on the rightmost path: [w] is the open rightmost path up to the rightmost head's
    open bracket, then j closing brackets and M's close X (j does not matter for the next chop). *)
Inductive HRep : list tree -> list pr -> Prop :=
| HR_nil : HRep [] [pX]
| HR_sp : forall sp j, sp <> [] -> HRep (plug sp []) (wsp sp ++ repeat pC j ++ [pX]).

Lemma HR_sp' : forall sp j w, sp <> [] -> w = wsp sp ++ repeat pC j ++ [pX] -> HRep (plug sp []) w.
Proof. intros; subst; constructor; assumption. Qed.

(** M = the root. *)
Lemma HRep_root : forall hs, HRep hs (encL hs ++ [pX]).
Proof.
  intros [|t hs]; [constructor|].
  destruct (spine_exists (t :: hs) ltac:(discriminate)) as [sp [Hsp ->]].
  apply (HR_sp' sp (length sp)); [exact Hsp|].
  rewrite enc_plug. change (encL []) with (@nil pr). rewrite <- !app_assoc. reflexivity.
Qed.

(** M = the last child of the node with children [L2 ++ [M]] at the end of the spine sp0. *)
Lemma HRep_open : forall sp0 L2 L',
  HRep (plug sp0 (L2 ++ [node L'])) (wsp sp0 ++ encL L2 ++ [pO] ++ encL L' ++ [pX]).
Proof.
  intros sp0 L2 [|t L'].
  - change (L2 ++ [node []]) with (plug [L2] []). rewrite <- plug_app.
    apply (HR_sp' _ 0); [destruct sp0; discriminate|].
    rewrite wsp_app, wsp_single. change (encL []) with (@nil pr). rewrite <- !app_assoc. reflexivity.
  - destruct (spine_exists (t :: L') ltac:(discriminate)) as [sp' [Hsp' E']]. rewrite E'.
    change (L2 ++ [node (plug sp' [])]) with (plug (L2 :: sp') []). rewrite <- plug_app.
    apply (HR_sp' _ (length sp')); [destruct sp0; discriminate|].
    rewrite enc_plug, wsp_app. change (wsp (L2 :: sp')) with ((encL L2 ++ [pO]) ++ wsp sp').
    change (encL []) with (@nil pr). rewrite <- !app_assoc. reflexivity.
Qed.

Lemma spine_cases : forall sp : list (list tree), sp <> [] ->
  (exists L0, sp = [L0]) \/ (exists sp0 L L', sp = sp0 ++ [L; L']).
Proof.
  intros sp H. destruct sp as [|L' sp1 _] using rev_ind; [congruence|].
  destruct sp1 as [|L sp0 _] using rev_ind; [left; exists L'; reflexivity|].
  right. exists sp0, L, L'. rewrite <- app_assoc. reflexivity.
Qed.

Lemma plug_root : forall L0, plug [L0] [] = L0 ++ [leaf].
Proof. reflexivity. Qed.

Lemma plug_deep : forall sp0 L L', plug (sp0 ++ [L; L']) [] = plug sp0 (L ++ [node (L' ++ [leaf])]).
Proof. intros. rewrite plug_app. reflexivity. Qed.

(** ** The two composite rounds C(m) -> C(m+1) *)

(** Successor: the rightmost head is a child of the root; it is removed. *)
Lemma round_succ : forall m L0 j, Forall (hb E) L0 ->
  Cf m (wsp [L0] ++ repeat pC j ++ [pX]) -->+ Cf (S m) (encL L0 ++ [pX]).
Proof.
  intros m L0 j H. unfold Cf. rewrite wsp_single, <- app_assoc.
  eapply progress_evstep_trans; [apply R2root; exact H|].
  apply (R1'_iter (S m) 0 L0 H).
Qed.

(** Limit: the rightmost head is a child of p = node (L' ++ [leaf]) (not the root); p is replaced
    by m+3 copies of the shortened p in its parent (children L ++ [p]). *)
Lemma round_lim : forall m sp0 L L' j, Forall (hb E) (plug sp0 (L ++ [node (L' ++ [leaf])])) ->
  exists w', HRep (plug sp0 (L ++ repeat (node L') (m + 3))) w' /\
             Cf m (wsp (sp0 ++ [L; L']) ++ repeat pC j ++ [pX]) -->+ Cf (S m) w'.
Proof.
  intros m sp0 L L' j H.
  assert (HL' : Forall (hb (pred E)) L') by (apply (hb_parent sp0 (pred E) L L'); exact H).
  assert (HE : pred E < E) by (unfold E; lia).
  exists (wsp sp0 ++ encL (L ++ repeat (node L') (S (S m))) ++ [pO] ++ encL L' ++ [pX]). split.
  { replace (m + 3) with (S (S (S m))) by lia.
    rewrite (repeat_snoc (node L') (S (S m))), app_assoc. apply HRep_open. }
  unfold Cf.
  replace (wsp (sp0 ++ [L; L']) ++ repeat pC j ++ [pX])
    with ((wsp sp0 ++ encL L) ++ [pO] ++ encL L' ++ [pO] ++ repeat pC j ++ [pX])
    by (rewrite wsp_app; unfold wsp at 2; simpl; rewrite !app_nil_r, <- !app_assoc; reflexivity).
  eapply progress_evstep_trans; [apply (R2 (pred E)); [oc | exact HL' | exact HE]|].
  replace ((wsp sp0 ++ encL L) ++ [pO] ++ encL L' ++ [pC; pO] ++ encL L' ++ [pX])
    with (((wsp sp0 ++ encL L) ++ [pO] ++ encL L' ++ [pC]) ++ [pO] ++ encL L' ++ [pX])
    by (rewrite <- !app_assoc; reflexivity).
  eapply evstep_trans; [apply (R1_iter (pred E) (S m) 0); [oc | exact HL' | exact HE]|].
  rewrite encL_app, encL_repeat, enc_node. cbn [lpow Nat.add]. rewrite <- !app_assoc. apply evstep_refl.
Qed.

(** ** Ones on the tape (as in BB11/verify/multifile/BB11_M11b_fgh.v and BB29/verify/multifile/BB29_bound.v) *)

Definition sym_val (s : Sym) : nat := match s with S0 => 0 | S1 => 1 end.

Fixpoint count1 (xs : list Sym) : nat :=
  match xs with [] => 0 | x :: t => sym_val x + count1 t end.

(** [ones c N]: the tape of [c] is a finite word padded with 0s on both sides, with N ones. *)
Definition ones (c : Q * tape) (N : nat) : Prop :=
  exists (q : Q) (L R : list Sym) (s : Sym),
    c = (q, (L *> const S0, s, R *> const S0)) /\ N = count1 L + sym_val s + count1 R.

Lemma count1_app : forall xs ys, count1 (xs ++ ys) = count1 xs + count1 ys.
Proof. induction xs; intros; simpl; [reflexivity | rewrite IHxs; lia]. Qed.

Lemma count1_pow : forall xs n, count1 (xs ^^ n) = n * count1 xs.
Proof. induction n; simpl; [reflexivity | rewrite count1_app, IHn; lia]. Qed.

Lemma ls_repeatO : forall n l, ls l (repeat pO n) = [1; 0]^^n *> l.
Proof.
  induction n as [|n IH]; intros l; [reflexivity|].
  cbn [repeat ls]. rewrite IH. change (bL pO) with [1; 0 : Sym].
  rewrite <- Str_app_assoc, lpow_shift. reflexivity.
Qed.

Lemma ones_c_end : forall a, ones (c_end a) (S a).
Proof.
  intros a. exists rB, (0 :: [1; 0]^^(S a)), [0; 0], 0. split.
  - unfold c_end. rewrite ls_snoc, ls_repeatO. reflexivity.
  - cbn [count1 sym_val]. rewrite count1_pow. cbn [count1 sym_val]. lia.
Qed.

(** ** The game *)

Definition Pg (x : ord) (n : nat) : Prop :=
  exists m hs w, n = m + 3 /\ x = olist hs /\ Forall (hb E) hs /\ HRep hs w /\ c0 -->* Cf m w.

Definition Wg (v : nat) : Prop :=
  exists c N, c0 -->* c /\ halted tm c /\ ones c N /\ v <= N + 2.

Theorem game : forall x n, nf x -> 1 <= n -> Pg x n -> Wg (HH x n).
Proof.
  apply hardy_game.
  - intros a b Hba (c & N & H1 & H2 & H3 & H4). exists c, N. repeat split; try assumption. lia.
  - (* zero: the empty hydra, rule R3 *)
    intros n (m & hs & w & -> & Hx & Hb & Hr & Hc).
    destruct Hr as [|sp j Hsp].
    + exists (c_end m), (S m). split; [eapply evstep_trans; [exact Hc | apply progress_evstep, R3]|].
      split; [apply c_end_halted|]. split; [apply ones_c_end | lia].
    + exfalso. symmetry in Hx. exact (olist_plug_ne sp [] Hsp Hx).
  - (* successor *)
    intros x b n Hnx Hk Hn (m & hs & w & -> & -> & Hb & Hr & Hc).
    destruct Hr as [|sp j Hsp]; [discriminate|].
    destruct (spine_cases sp Hsp) as [[L0 ->] | (sp0 & L & L' & ->)].
    + rewrite plug_root, olist_leaf_snoc, okind_osucc in Hk. injection Hk as <-.
      rewrite plug_root in Hb. apply Forall_app in Hb as [Hb _].
      exists (S m + 3). split; [lia|].
      exists (S m), L0, (encL L0 ++ [pX]).
      split; [reflexivity|]. split; [reflexivity|]. split; [exact Hb|]. split; [apply HRep_root|].
      eapply evstep_trans; [exact Hc | apply progress_evstep, round_succ; exact Hb].
    + rewrite plug_deep in Hk. rewrite (proj1 (chop_ord sp0 L L' 0)) in Hk. discriminate.
  - (* limit *)
    intros x n Hnx Hk Hn (m & hs & w & -> & -> & Hb & Hr & Hc).
    destruct Hr as [|sp j Hsp]; [discriminate|].
    destruct (spine_cases sp Hsp) as [[L0 ->] | (sp0 & L & L' & ->)].
    + rewrite plug_root, olist_leaf_snoc, okind_osucc in Hk. discriminate.
    + rewrite plug_deep in Hb, Hk |- *.
      destruct (chop_ord sp0 L L' (m + 3)) as [_ [Hlt Hle]].
      destruct (round_lim m sp0 L L' j Hb) as (w' & Hr' & Hstep).
      exists (olist (plug sp0 (L ++ repeat (node L') (m + 3)))), 1%nat, (S m + 3).
      split; [apply nf_olist|]. split; [exact Hlt|].
      split; [apply desc_between; [apply nf_olist | apply nf_olist | exact Hle | exact Hlt]|].
      split; [lia|]. split; [lia|].
      exists (S m), (plug sp0 (L ++ repeat (node L') (m + 3))), w'.
      split; [reflexivity|]. split; [reflexivity|].
      split; [eapply hb_plug_repl; [| exact Hb]; intros h'; apply hb_chop|].
      split; [exact Hr'|].
      eapply evstep_trans; [exact Hc | apply progress_evstep, Hstep].
Qed.
