def banner(name):
    return "(* %s *)" % name


def tm_file(m, name, root):
    states = " | ".join(m.states())
    syms = " | ".join(m.sym_names())
    all_qs = "; ".join(m.states())
    all_syms = "; ".join(m.sym_names())
    return """(** * Instantiating busycoq to machines with %d states and %d symbols *)

From Coq Require Import Lists.List. Import ListNotations.
From BusyCoq Require Export TM.
Set Default Goal Selector "!".

Inductive state := %s.
Inductive sym := %s.

Module %s <: Ctx.
  Definition Q := state.
  Definition Sym := sym.
  Definition q0 := A.
  Definition q1 := %s.
  Definition s0 := S0.
  Definition s1 := S1.

  Lemma q0_neq_q1 : q0 <> q1.
  Proof. discriminate. Qed.

  Lemma s0_neq_s1 : s0 <> s1.
  Proof. discriminate. Qed.

  Definition eqb_q (a b : Q): {a = b} + {a <> b}.
    decide equality.
  Defined.

  Definition eqb_sym (a b : Sym): {a = b} + {a <> b}.
    decide equality.
  Defined.

  Definition all_qs := [%s].
  Lemma all_qs_spec : forall a, In a all_qs.
  Proof.
    destruct a; repeat ((left; reflexivity) || right).
  Qed.

  Definition all_syms := [%s].
  Lemma all_syms_spec : forall a, In a all_syms.
  Proof.
    destruct a; repeat ((left; reflexivity) || right).
  Qed.
End %s.
""" % (m.nstates, m.nsyms, states, syms, name, m.states()[1], all_qs, all_syms, name)


def individual_file(m, name, root):
    notations = "\n".join('Notation "%d" := S%d : sym_scope.' % (j, j)
                          for j in range(m.nsyms))
    # NB: the head notations contain braces, so they are built by concatenation
    # rather than by %-formatting (where {{ and }} would need escaping).
    heads = "\n".join(
        'Notation "l \'{{' + s + '}}>\'  r" := (l {{' + s + '}}> r) (at level 30).'
        for s in m.states())
    lefts = "\n".join(
        'Notation "l \'<{{' + s + '}}\' r" := (l <{{' + s + '}} r) (at level 30).'
        for s in m.states())
    indiv = name[len("BB"):] if name.startswith("BB") else name
    return """From BusyCoq Require Export Individual.
From @ROOT@ Require Export @NAME@.

Module Individual@INDIV@ := Individual @NAME@.
Export Individual@INDIV@.

Declare Scope sym_scope.
Bind Scope sym_scope with Sym.
Delimit Scope sym_scope with sym.
Open Scope sym.

@NOTATIONS@

(* Make sure that [{{A}}>] still refers to the state, even if we shadowed
   [A] itself with something else. *)
@HEADS@
@LEFTS@
""".replace("@ROOT@", root).replace("@NAME@", name) \
   .replace("@INDIV@", indiv).replace("@NOTATIONS@", notations) \
   .replace("@HEADS@", heads).replace("@LEFTS@", lefts)


def rules_file(m, name, root, indiv):
    return """(** * Rules for %s *)

(** Tape convention (busycoq): [l <{{Q}} r] has the head on [hd l];
    [l {{Q}}> r] has the head on [hd r].  A left stream is listed from the
    head outwards.  The halting transition is the only [None] entry of [tm]. *)

From %s Require Import %s.
From Coq Require Import Lia PeanoNat List.
Import ListNotations.
Set Default Goal Selector "!".

(* machine: %s *)
%s

Notation "c --> c'" := (c -[ tm ]-> c')   (at level 40).
Notation "c -->* c'" := (c -[ tm ]->* c') (at level 40).
Notation "c -->+ c'" := (c -[ tm ]->+ c') (at level 40).

(** ** Elementary sweeps

    Each sweep is a small "the machine walks over a block of symbols and
    rewrites it" lemma, proved by a plain induction on the block length:

      Lemma C_sweep_left : forall j l r,
        ([2]^^j *> l) <{{C}} r -->* l <{{C}} ([3]^^j *> r).
      Proof.
        induction j as [|j IH]; intros l r.
        - finish.
        - step. follow (IH l (3 >> r)). finish_norm.
      Qed.

    with

      Ltac norm_nat := repeat progress (rewrite ?Nat.add_succ_r, ?Nat.add_0_r; simpl).
      Ltac finish_norm := apply evstep_refl'; norm_nat; try (rewrite lpow_snoc); try reflexivity; lia_refl.
      Ltac st_tape := autorewrite with tape_pre; simpl.
      Ltac st_step := (eapply evstep_step || eapply progress_step); [prove_step | st_tape].

    ** TODO: replace the sweeps by the ones of this machine. ** *)

(** ** The configuration family of the machine

    TODO: define the configuration family, e.g.

      Definition Bcfg (k n m : nat) (r : Stream sym) : Q * tape :=
        ([2]^^k *> [3]^^(2 * m + 1) *> const 0) {{A}}> ([1]^^n *> r).

    ** ** The main rule

    TODO: state and prove the rule of the machine by double induction, e.g.

      Theorem B_rule : forall k n m r,
        Bcfg (S k) n m r -->* Bcfg (S k) 0 (Nat.iter n (g k) m) r.

    ** ** The recursion function

    TODO: define the function whose closed form gives the score, e.g.

      Fixpoint g (k m : nat) : nat :=
        match k with
        | O => S m
        | S k' => Nat.iter (2 * m + 2) (g k') 0%%nat
        end.
    *)
""" % (m.spec, root, indiv, m.spec, coq_table(m))


def run_file(m, name, root, indiv):
    return """(** * The run of %s, its halting configuration, and the score *)

From %s Require Import %s %s_rules %s_start.
From Coq Require Import Lia PeanoNat List.
Import ListNotations.
Set Default Goal Selector "!".

(** ** The start

    TODO: after generating %s_start.v with tools/gen_start_chunks.py, tie the
    generated [start_raw] to the machine's own configuration notation:

      Lemma start : c0 -->* <the configuration the run reaches>.
      Proof.
        rewrite <- <the generated equality>.
        apply start_raw.
      Qed.

    ** ** The score-carrying number

    ** The number that determines the score is usually astronomically large and
    its term is NOT evaluable.  Seal it behind a [sig] so that [simpl] and
    [lia] treat it as an opaque atom:

      Lemma g15_spec : {x : nat | x = <the term>}.
      Proof. exact (exist _ _ eq_refl). Qed.
      Definition g15 : nat := proj1_sig g15_spec.
      Lemma g15_eq : g15 = <the term>.
      Proof. exact (proj2_sig g15_spec). Qed.

    ** ** The rules, abstracted

    ** Where a rule of %s_rules.v produces the huge term, abstract it so that no
    conversion between the sealed [g15] and the raw term is ever required:

      Theorem B_rule_gen : forall k n m r (x : nat),
        x = <the term> -> <the configuration family> -->* <the result with x>.

    ** ** The halting configuration

      Definition c_final : Q * tape := <the halting configuration>.

      Theorem reaches_final : c0 -->* c_final.
      Theorem final_halted : halted tm c_final.
      Theorem bb34_halts : halts tm c0.

    ** ** The score

      Definition sigma : nat := <the number of nonzero cells>.
      Definition final_cells : list sym := <the nonzero cells>.

      Prove the counting lemmas for an ABSTRACT parameter and only instantiate
      afterwards, so that no tactic ever looks at the sealed number:

        Lemma cells_count : forall x : nat, <count> = <count>.
        Lemma final_cells_count : length final_cells = sigma.
    *)
""" % (m.spec, root, indiv, name, name, name, indiv)


def score_file(m, name, root, indiv):
    return """(** * The score of %s *)

(** Main results:
      sigma_eq  : sigma = knuth 15 2 5 + 14   (i.e. 2 ↑^15 5 + 14)
      g_closed  : 2 * g_(k+1)(m) + 4 = knuth k 2 (2m+4)
    No large number is ever evaluated: [knuth 15 2 5] and the sealed [g15]
    stay symbolic throughout. *)

From %s Require Import %s %s_rules %s_run.
From Coq Require Import Lia PeanoNat.
From Coq.micromega Require Import ZifyNat.
Local Open Scope nat_scope.
Set Default Goal Selector "!".

(** ** Knuth up-arrows: [knuth n a b = a ↑^n b], with [a ↑^0 b = a * b] *)
Fixpoint knuth (n a b : nat) : nat :=
  match n with
  | 0 => a * b
  | S n' => Nat.iter b (knuth n' a) 1
  end.

Lemma iter_add : forall (f : nat -> nat) a b x,
  Nat.iter (a + b) f x = Nat.iter a f (Nat.iter b f x).
Proof.
  induction a as [|a IH]; intros b x.
  - reflexivity.
  - simpl. rewrite IH. reflexivity.
Qed.

Lemma knuth_S0 : forall k b, knuth (S k) 2 b = Nat.iter b (knuth k 2) 1.
Proof. reflexivity. Qed.

(** The coincidence 2 ↑^k 2 = 4 for all k, on which the closed form rests. *)
Lemma knuth_1 : forall k, knuth k 2 1 = 2.
Proof.
  induction k as [|k IH].
  - reflexivity.
  - simpl. exact IH.
Qed.

Lemma knuth_2 : forall k, knuth k 2 2 = 4.
Proof.
  induction k as [|k IH].
  - reflexivity.
  - simpl. rewrite knuth_1. exact IH.
Qed.

Lemma iter2_knuth : forall k, Nat.iter 2 (knuth k 2) 1 = 4.
Proof. intros k. simpl. rewrite knuth_1. apply knuth_2. Qed.

(** ** The closed form of the recursion: 2 g_(k+1)(m) + 4 = 2 ↑^k (2m+4)

    TODO: adapt to this machine's recursion function [g] and its induction. *)

Section ClosedForm.

Variable h kh : nat -> nat.
Hypothesis hyp : forall y, 2 * h y + 4 = kh (2 * y + 4).

Lemma iter_closed_helper : forall j x,
  2 * Nat.iter j h x + 4 = Nat.iter j kh (2 * x + 4).
Proof.
  induction j as [|j IH]; intros x.
  - simpl. lia.
  - simpl in *. rewrite hyp. rewrite (IH x). reflexivity.
Qed.

End ClosedForm.

(** ** The exact score: sigma = (2 ↑^15 5) + 14

    TODO: adjust the indices to this machine.  The pattern to follow:

      Theorem g_iter_closed : forall k n,
        2 * Nat.iter n (g k) 0%%nat + 4 = knuth k 2 (n + 2).

      Theorem g_iter_closed_gen : forall k n (x : nat),
        x = Nat.iter n (g k) 0%%nat -> 2 * x + 4 = knuth k 2 (n + 2).
      Proof. intros k n x Hx. subst x. apply g_iter_closed. Qed.

      Lemma g15_closed : 2 * g15 + 4 = knuth 15 2 5.
      Proof. exact (g_iter_closed_gen 15 3 g15 g15_eq). Qed.

      Lemma score_generic : forall (x K : nat),
        2 * x + 4 = K -> 2 * x + 18 = K + 14.
      Proof. intros x K H. lia. Qed.

      Theorem sigma_eq : sigma = knuth 15 2 5 + 14.
      Proof.
        unfold sigma.
        apply (score_generic g15 (knuth 15 2 5)).
        exact g15_closed.
      Qed.
    *)
""" % (m.spec, root, indiv, name, name)


def probe_file(m, name, root, indiv, nstates, nsyms):
    rowlen = 3 * nsyms
    width = rowlen + 1
    machine = m.spec
    qs = ("Definition qi (q : state) : nat := match q with %s end."
          % " | ".join("%s => %d" % (st, i) for i, st in enumerate(m.states())))
    ss = ("Definition si (s : sym) : nat := match s with %s end."
          % " | ".join("S%d => %d" % (j, j) for j in range(nsyms)))
    sym_cases = "\n".join('  | "%d"%%char => Some S%d' % (j, j) for j in range(nsyms))
    state_cases = "\n".join('  | "%s"%%char => Some (Some %s)' % (s, s) for s in m.states())
    underscores = " /\\\n".join(
        "  String.get %d machine = Some \"_\"%%char" % (i * width - 1)
        for i in range(1, nstates))
    halt_off, halt_txt = m.halt_entry_pos()
    return """(** Independent probe: the Coq table [tm] equals the machine string, and the main
    theorems are axiom-free.  Requires all of %s to compile first. *)
From %s Require Import %s %s_rules %s_start %s_run %s_score.
From Coq Require Import String Ascii List.
Import ListNotations.
Open Scope string_scope.

Definition machine : string := "%s".

%s
%s
Definition sym_of (c : ascii) : option sym :=
  match c with
%s
  | _ => None end.
Definition dir_of (c : ascii) : option dir :=
  match c with
  | "L"%%char => Some L | "R"%%char => Some R | _ => None end.
(** [Some (Some q)] = go to q; [Some None] = halt (Z); [None] = parse error *)
Definition st_of (c : ascii) : option (option state) :=
  match c with
%s
  | "Z"%%char => Some None | _ => None end.

(** Each row has %d characters (%d symbols x 3), rows separated by "_".
    The rows therefore start at 0, %d, ... , so k = %d * qi + 3 * si. *)
Definition parsed (q : state) (s : sym) : option (option (sym * dir * state)) :=
  let k := %d * qi q + 3 * si s in
  match String.get k machine, String.get (k + 1) machine, String.get (k + 2) machine with
  | Some c1, Some c2, Some c3 =>
    match sym_of c1, dir_of c2, st_of c3 with
    | Some w, Some d, Some (Some q') => Some (Some (w, d, q'))
    | Some _, Some _, Some None => Some None
    | _, _, _ => None
    end
  | _, _, _ => None
  end.

Lemma underscores :
  %s /\\
  String.length machine = %d.
Proof. vm_compute. repeat split. Qed.

Lemma halt_entry : String.substring %d 3 machine = "%s".
Proof. vm_compute. reflexivity. Qed.

Lemma table_matches_string : forall q s, Some (tm (q, s)) = parsed q s.
Proof. intros [] []; vm_compute; reflexivity. Qed.

Lemma c0_is_blank_A : c0 = (A, (Streams.const S0, S0, Streams.const S0)).
Proof. reflexivity. Qed.

(** The statements of the main results, for the record. *)
Check bb34_halts.
Check reaches_final.
Check final_halted.
Check sigma_eq.
Check bb34_main.

Print Assumptions underscores.
Print Assumptions halt_entry.
Print Assumptions table_matches_string.
Print Assumptions c0_is_blank_A.
Print Assumptions bb34_halts.
Print Assumptions reaches_final.
Print Assumptions final_halted.
Print Assumptions sigma_eq.
Print Assumptions bb34_main.
""" % (root, root, indiv, name, name, name, name,
       machine, qs, ss, sym_cases, state_cases,
       rowlen, nsyms, width, width, width,
       underscores, len(machine),
       halt_off if halt_off is not None else 0,
       halt_txt if halt_txt is not None else "1RZ")


def compile_script(name, root, indiv):
    files = [name, indiv, "%s_rules" % name, "%s_start" % name, "%s_run" % name,
             "%s_score" % name]
    lst = " ".join(files)
    return """#!/bin/bash
# Clean compile of the %s proofs against a busycoq checkout, in dependency order,
# then the probe.   BUSYCOQ=/path/to/busycoq/verify ./compile_clean.sh
# COQC may be set to a specific coqc executable.  The logical path of this directory is %s.
COQC=${COQC:-coqc}
if [ -z "$BUSYCOQ" ]; then
  echo "set BUSYCOQ to the verify/ directory of a busycoq checkout" >&2
  exit 2
fi
set -e
for f in %s; do
  echo "== $f.v =="
  start=$(date +%%s)
  "$COQC" -Q "$BUSYCOQ" BusyCoq -Q . %s "$f.v"
  echo "   ok, $(( $(date +%%s) - start )) s"
done
echo "COMPILE DONE"
"$COQC" -Q "$BUSYCOQ" BusyCoq -Q . %s probe.v > probe.log
echo "probe: $(grep -c 'Closed under the global context' probe.log) theorems closed under the global context"
grep -c 'Axioms' probe.log && echo "PROBLEM: axioms present" || echo "no axioms"
""" % (name, root, lst, root, root)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--machine", required=True)
    ap.add_argument("--outdir", required=True)
    ap.add_argument("--title", default=None, help="human readable title of the machine")
    ap.add_argument("--name", default=None, help="project name (default BB<states><symbols>)")
    ap.add_argument("--skip-busycoq", action="store_true",
                    help="do not copy the busycoq sources (they are fetched separately)")
    args = ap.parse_args()

    m = parse_machine(args.machine)
    name = args.name or ("BB%d%d" % (m.nstates, m.nsyms))
    root = "TM%d%d" % (m.nstates, m.nsyms)
    indiv = "Individual%d%d" % (m.nstates, m.nsyms)

    out = os.path.abspath(args.outdir)
    os.makedirs(os.path.join(out, "verify"), exist_ok=True)
    os.makedirs(os.path.join(out, "tools"), exist_ok=True)

    written = []
    for fn, content in (
        ("%s.v" % name, tm_file(m, name, root)),
        ("%s.v" % indiv, individual_file(m, name, root)),
        ("%s_rules.v" % name, rules_file(m, name, root, indiv)),
        ("%s_run.v" % name, run_file(m, name, root, indiv)),
        ("%s_score.v" % name, score_file(m, name, root, indiv)),
        ("probe.v", probe_file(m, name, root, indiv, m.nstates, m.nsyms)),
        ("compile_clean.sh", compile_script(name, root, indiv)),
    ):
        path = os.path.join(out, "verify", fn)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(content)
        written.append(os.path.join("verify", fn))

    with open(os.path.join(out, "verify", "_CoqProject"), "w",
              encoding="utf-8", newline="\n") as fh:
        fh.write("-Q . %s\n-Q ../../busycoq/verify BusyCoq\n" % root)
        for f in ("%s.v" % name, "%s.v" % indiv, "%s_rules.v" % name,
                  "%s_start.v" % name, "%s_run.v" % name, "%s_score.v" % name):
            fh.write(f + "\n")

    # copy the helper scripts
    here = os.path.dirname(os.path.abspath(__file__))
    for s in ("tm_lib.py", "gen_start_chunks.py", "init_tm_project.py", "tm_sim.py"):
        src = os.path.join(here, s)
        if os.path.exists(src):
            shutil.copy2(src, os.path.join(out, "tools", s))

    if not args.skip_busycoq:
        bc = os.path.join(out, "busycoq", "verify")
        os.makedirs(bc, exist_ok=True)
        with open(os.path.join(out, "busycoq", "README.md"), "w",
                  encoding="utf-8", newline="\n") as fh:
            fh.write("busycoq (https://github.com/meithecatte/busycoq) at commit bd2e36f -- only\n"
                     "the seven verify/ files needed by %s are included; clone the repository for\n"
                     "the full history.\n"
                     "Build: cd verify && for f in LibTactics Helper TM Compute Flip Permute Individual; do coqc -Q . BusyCoq $f.v; done\n"
                     % name)

    title = args.title or ("BB(%d,%d)" % (m.nstates, m.nsyms))
    with open(os.path.join(out, "README.md"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("# %s\n\n"
                 "Coq/busycoq proof that the Turing machine `%s` halts.\n\n"
                 "    0    1    2    3\n"
                 "A   ...\n\n"
                 "See [verify/README.md](verify/README.md).\n"
                 % (title, m.spec))

    print("scaffolded %s in %s" % (name, out))
    print("  state/symbol count : %d states, %d symbols" % (m.nstates, m.nsyms))
    print("  files              : %s" % ", ".join(written))
    print("")
    print("next steps:")
    print("  1. copy the 7 busycoq files into busycoq/verify/ and compile them")
    print("     (cd busycoq/verify && for f in LibTactics Helper TM Compute Flip Permute Individual; do coqc -Q . BusyCoq $f.v; done)")
    print("  2. fill in %s_rules.v: the elementary sweeps, the configuration family," % name)
    print("     the recursion function g and the main rule (by double induction)")
    print("  3. generate %s_start.v:" % name)
    print("     python tools/gen_start_chunks.py --machine %s --steps <N> --chunk 10 \\" % m.spec)
    print("         --root %s --out verify/%s_start.v" % (root, name))
    print("  4. fill in %s_run.v (c_final, reaches_final, final_halted, bb34_halts, sigma)" % name)
    print("  5. fill in %s_score.v (g_closed, g_iter_closed, g15_closed, sigma_eq)" % name)
    print("  6. cd verify && BUSYCOQ=../busycoq/verify ./compile_clean.sh")


if __name__ == "__main__":
    main()
