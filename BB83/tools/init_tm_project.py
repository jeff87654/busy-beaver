#!/usr/bin/env python3
"""Scaffold a complete Coq/busycoq project that proves a Turing machine halts.

The generated project has the layout used by jeff87654/busy-beaver:

    README.md
    <machine>.md
    verify/TMxx.v            busycoq instantiation for this state/symbol count
    verify/Individualxx.v    notations
    verify/TMxx_rules.v      transition table + the rules of the machine  (to fill in)
    verify/TMxx_start.v      generated by gen_start_chunks.py             (to generate)
    verify/TMxx_run.v        the halting configuration and the run        (to fill in)
    verify/TMxx_score.v      the Knuth-arrow closed form and the score    (to fill in)
    verify/probe.v           independent checks + Print Assumptions
    verify/compile_clean.sh  build script
    verify/_CoqProject
    tools/                   simulator and generators
    busycoq/verify/          the busycoq files the proof needs

Usage
-----
    python init_tm_project.py --machine 1RB3LB1RZ2RA_2LC3RB1LC2RA_3RB1LB3LC2RC \\
        --outdir ../BB34-proof --title "BB(3,4) champion"

    python init_tm_project.py --machine ... --outdir ... --skip-busycoq
"""

