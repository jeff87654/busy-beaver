#!/usr/bin/env python3
"""Generate the chunked Coq proof of the run of a Turing machine from the blank tape.

Why chunking is necessary
-------------------------
busycoq's ``execute`` tactic is

    Ltac execute := introv; repeat (try solve [finish]; step).

``step`` ends in ``simpl_tape`` (``autorewrite with tape_pre; simpl; autorewrite
with tape_post``) and ``autorewrite`` rewrites the *whole goal*.  In the middle
of an ``execute`` the goal contains every intermediate tape accumulated so far,
so a single ``execute`` over n steps performs O(n^2) tape rewrites over tapes
of size O(n): it is cubic.  A 241-step ``execute`` was measured at >15 GB of
RAM and never terminating.

Cutting the run into chunks of ``--chunk`` steps keeps the accumulated term
short: the cost becomes linear and the file compiles in seconds.

Usage
-----
    python gen_start_chunks.py --machine 1RB3LB1RZ2RA_2LC3RB1LC2RA_3RB1LB3LC2RC \\
        --steps 241 --chunk 10 --root TM34 --out verify/BB34_start.v

The script also prints the configuration reached after ``--steps`` steps, so it
can be pasted into the run/score files.
"""

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from tm_lib import blank, coq_config, coq_sym, parse_machine  # noqa: E402


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--machine", required=True,
                    help='TNF machine string, e.g. "1RB3LB1RZ2RA_2LC3RB1LC2RA_3RB1LB3LC2RC"')
    ap.add_argument("--steps", type=int, required=True,
                    help="number of steps to run from the blank tape")
    ap.add_argument("--chunk", type=int, default=10, help="steps per chunk (default 10)")
    ap.add_argument("--root", default="TM", help="logical Coq path of the directory (default TM)")
    ap.add_argument("--prefix", default="cfg", help="name prefix of the configuration definitions")
    ap.add_argument("--out", required=True, help="output .v file")
    ap.add_argument("--states", default=None,
                    help="comma separated state constructors to require (default: from the machine)")
    ap.add_argument("--imports", default="",
                    help="comma separated additional modules of the same logical path to "
                         "import (e.g. BB34_rules, needed when --final-eq mentions them)")
    ap.add_argument("--final-eq-name", default=None,
                    help="name of the generated equality lemma (default: <prefix>_<steps>_eq)")
    ap.add_argument("--final-eq", default=None,
                    help="a Coq term equal to the final configuration; the generator then "
                         "emits the lemma <prefix>_<steps>_eq : <prefix>_<steps> = <term>")
    args = ap.parse_args()

    m = parse_machine(args.machine)
    if args.states:
        want = [s.strip() for s in args.states.split(",")]
        if want != m.states():
            print("WARNING: machine has states %s, but %s were requested"
                  % (m.states(), want), file=sys.stderr)

    # -- simulate ---------------------------------------------------------
    cfgs = [blank(m)]
    c = cfgs[0].copy()
    for _ in range(args.steps):
        if not c.step(m):
            raise SystemExit("the machine halted before step %d" % args.steps)
        cfgs.append(c.copy())

    points = list(range(0, args.steps + 1, args.chunk))
    if points[-1] != args.steps:
        points.append(args.steps)

    # -- emit -------------------------------------------------------------
    out = []
    out.append("(** * The %d-step run of %s from the blank tape." % (args.steps, m.spec))
    out.append("")
    out.append("    GENERATED by scripts/gen_start_chunks.py -- do not edit by hand.")
    out.append("")
    out.append("    The run is cut into chunks of %d steps; each chunk is discharged by" % args.chunk)
    out.append("    busycoq's [execute].  Chunking is not cosmetic: [execute] re-normalises")
    out.append("    the whole accumulated proof term at every step, so one monolithic")
    out.append("    %d-step [execute] is cubic and exhausts the memory of coqc, while the" % args.steps)
    out.append("    chunked version compiles in seconds.  The intermediate configurations")
    out.append("    below were produced by the simulator; Coq re-derives each of them from")
    out.append("    scratch. *)")
    out.append("")
    indiv = args.root[len("TM"):] if args.root.startswith("TM") else ""
    extra = [x.strip() for x in args.imports.split(",") if x.strip()]
    imports = " ".join(["Individual%s" % indiv] + extra)
    out.append("From %s Require Import %s." % (args.root, imports))
    out.append("From Coq Require Import Lia PeanoNat List.")
    out.append("Import ListNotations.")
    out.append('Set Default Goal Selector "!".')
    out.append("")

    for p in points:
        out.append("Definition %s_%d : Q * tape := %s."
                   % (args.prefix, p, coq_config(cfgs[p])))
    out.append("")

    for i in range(len(points) - 1):
        a, b = points[i], points[i + 1]
        out.append("Lemma chunk_%d : %s_%d -->* %s_%d." % (i, args.prefix, a, args.prefix, b))
        out.append("Proof. unfold %s_%d, %s_%d. execute. Qed." % (args.prefix, a, args.prefix, b))
        out.append("")

    out.append("Lemma start_raw : c0 -->* %s_%d." % (args.prefix, args.steps))
    out.append("Proof.")
    out.append("  unfold c0, tape0, %s_%d." % (args.prefix, args.steps))
    for i in range(len(points) - 1):
        out.append("  follow (chunk_%d)." % i)
    out.append("  finish.")
    out.append("Qed.")
    out.append("")
    if args.final_eq:
        out.append("(** The configuration reached after %d steps, in the notation of the" % args.steps)
        out.append("    machine's own files. *)")
        name = args.final_eq_name or ("%s_%d_eq" % (args.prefix, args.steps))
        out.append("Lemma %s : %s_%d = %s."
                   % (name, args.prefix, args.steps, args.final_eq))
        out.append("Proof. reflexivity. Qed.")
        out.append("")

    text = "\n".join(out)
    os.makedirs(os.path.dirname(os.path.abspath(args.out)) or ".", exist_ok=True)
    with open(args.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)

    # -- report -----------------------------------------------------------
    final = cfgs[args.steps]
    print("wrote %s (%d chunks of <= %d steps)" % (args.out, len(points) - 1, args.chunk))
    print("")
    print("configuration after %d steps:" % args.steps)
    print("  state  :", final.state)
    print("  head   :", coq_sym(final.cur))
    print("  left   :", coq_config(final).split(", (")[1].split(",")[0])
    print("  right  :", coq_config(final).rsplit(", ", 1)[1].rstrip(")"))
    print("  word   :", final.word())
    print("")
    print("Coq term of the final configuration:")
    print("  ", coq_config(final))
    print("")
    print("Reminder: the generated file needs the run's `c0` to be state A on the blank")
    print("tape, i.e. the machine must be instantiated with q0 := A and s0 := S0.")


if __name__ == "__main__":
    main()
