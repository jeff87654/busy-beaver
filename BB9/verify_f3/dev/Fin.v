    eapply reach_extF; [exact HR | | | |].
    + replace (S L) with (5 * J + 20) by (unfold J; lia).
      replace (S (3 * J + 1)) with (3 * J + 2) by lia. apply AbsSUB5. lia.
    + lia.
    + unfold J. lia.
    + fin_tac.
Qed.

