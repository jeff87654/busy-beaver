Definition fin (l : side) : Prop := exists Ll : list Sym, l = Ll *> const 0.

Lemma fin_cons : forall (a : Sym) l, fin l -> fin (a >> l).
Proof. intros a l [Ll ->]. exists (a :: Ll). reflexivity. Qed.

Lemma fin_app : forall (xs : list Sym) l, fin l -> fin (xs *> l).
Proof. intros xs l [Ll ->]. exists (xs ++ Ll). rewrite Str_app_assoc. reflexivity. Qed.

Ltac fin_tac := repeat (first [assumption | apply fin_cons | apply fin_app]).

Definition reachF (Pm L : nat) : Prop :=
  exists t P s y l, c0 -->* D0f t (S L) P s y l /\ 1 <= y /\ Pm + L <= P /\ fin l.

Lemma reachF_P : forall Pm L, reachF Pm L -> reachP Pm L.
Proof. intros Pm L [t [P [s [y [l [H1 [H2 [H3 _]]]]]]]]. exists t, P, s, y, l. auto. Qed.

Lemma reach_extF : forall Pm n t P s y l t' P' s' y' l' L',
  c0 -->* D0f t n P s y l -> D0f t n P s y l -->+ D0f t' (S L') P' s' y' l' ->
  1 <= y' -> Pm + L' <= P' -> fin l' -> reachF Pm L'.
Proof.
  intros Pm n t P s y l t' P' s' y' l' L' H1 H2 Hy HP Hf.
  exists t', P', s', y', l'. split; [| split; [assumption | split; assumption]].
  eapply evstep_trans; [exact H1 | apply progress_evstep, H2].
Qed.

Theorem casc_stepF : forall Pm L, 60 <= L -> L mod 2 = 1%nat -> L mod 3 = 1%nat -> reachF Pm L -> reachF Pm (gstep L).
Proof.
  intros Pm L HL H2 H3 [t [P [s [y [l [HR [Hy [HP Hf]]]]]]]].
  destruct (split_mod L 3 ltac:(lia)) as [w [r3 [Hr3 HL3]]].
  rewrite (mod_of L 3 w r3 Hr3 HL3) in H3. subst r3. clear H2.
  destruct (split_mod L 5 ltac:(lia)) as [q [r [Hr HL5]]].
  unfold gstep. rewrite (mod_of L 5 q r Hr HL5).
  destruct r as [|[|[|[|[|r]]]]]; [| | | | | lia]; cbv beta iota.
  - (* r = 0: stop.  L = 5 (3 i + 2) + 30 (L = 1 mod 3) *)
    destruct (split_mod q 3 ltac:(lia)) as [i0 [d [Hd Hq]]].
    assert (d = 2%nat) by lia. subst d.
    set (i := i0 - 2). assert (Li : L = 5 * (3 * i + 2) + 30) by (unfold i; lia).
    replace ((3 * L - 100) / 5) with (3 * (3 * i + 2) - 2).
    2:{ symmetry. apply div5_eq. lia. }
    destruct (step_stop i P s t y l ltac:(lia) Hy) as [R HS].
    eapply reach_extF; [exact HR | | | |].
    + replace (S L) with (5 * (3 * i + 2) + 31) by lia.
      replace (S (3 * (3 * i + 2) - 2)) with (3 * (3 * i + 2) - 1) by lia. exact HS.
    + lia.
    + lia.
    + fin_tac.
  - (* r = 1: residue c = 2 *)
    set (J := q - 8).
    replace ((3 * L + 32) / 5) with (3 * J + 31) by (symmetry; apply div5_eq; unfold J; lia).
    eapply reach_extF; [exact HR | | | |].
    + replace (S L) with (5 * J + 42) by (unfold J; lia).
      replace (S (3 * J + 31)) with (3 * J + 32) by lia. apply AbsSUB2. lia.
    + lia.
    + unfold J. lia.
    + fin_tac.
  - (* r = 2: residue c = 3 *)
    set (J := q - 3).
    replace ((3 * L - 46) / 5) with (3 * J + 1) by (symmetry; apply div5_eq; unfold J; lia).
    eapply reach_extF; [exact HR | | | |].
    + replace (S L) with (5 * J + 18) by (unfold J; lia).
      replace (S (3 * J + 1)) with (3 * J + 2) by lia. apply AbsSUB3. lia.
    + lia.
    + unfold J. lia.
    + fin_tac.
  - (* r = 3: residue c = 4 *)
    set (J := q - 4).
    replace ((3 * L - 64) / 5) with (3 * J + 1) by (symmetry; apply div5_eq; unfold J; lia).
    eapply reach_extF; [exact HR | | | |].
    + replace (S L) with (5 * J + 24) by (unfold J; lia).
      replace (S (3 * J + 1)) with (3 * J + 2) by lia. apply AbsSUB4. lia.
    + lia.
    + unfold J. lia.
