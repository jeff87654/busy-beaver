Qed.

(** ** One g-step on the reachability predicate *)
Definition reachP (Pm L : nat) : Prop :=
  exists t P s y l, c0 -->* D0f t (S L) P s y l /\ 1 <= y /\ Pm + L <= P.

Lemma split_mod : forall n k, 0 < k -> exists q r, r < k /\ n = k * q + r.
Proof.
  intros n k Hk. exists (n / k), (n mod k). split; [apply Nat.mod_upper_bound; lia |].
  apply Nat.div_mod; lia.
Qed.

Lemma mod_of : forall n k q r, r < k -> n = k * q + r -> n mod k = r.
Proof.
  intros n k q r Hr ->. rewrite (Nat.add_comm (k * q) r), (Nat.mul_comm k q), Nat.Div0.mod_add.
  apply Nat.mod_small, Hr.
Qed.

Lemma reach_ext : forall Pm n t P s y l t' P' s' y' l' L',
  c0 -->* D0f t n P s y l -> D0f t n P s y l -->+ D0f t' (S L') P' s' y' l' ->
  1 <= y' -> Pm + L' <= P' -> reachP Pm L'.
Proof.
  intros Pm n t P s y l t' P' s' y' l' L' H1 H2 Hy HP.
  exists t', P', s', y', l'. split; [| split; assumption].
  eapply evstep_trans; [exact H1 | apply progress_evstep, H2].
Qed.

