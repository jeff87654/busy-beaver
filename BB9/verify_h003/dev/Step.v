    replace (4 + (y - 1)) with (3 + y) by lia. reflexivity. }
  rewrite E2.
  eapply evstep_trans; [apply progress_evstep, (AbsENTRY (J - 1) _ (y - 1) (P - 3) (2 + t) _ ltac:(lia)) |].
  replace (1 + (2 + t)) with (3 + t) by lia.
  replace (3 * (J - 1) + 2) with (3 * J - 1) by (unfold J; lia).
