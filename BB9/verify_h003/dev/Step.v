Lemma split6 : forall n, exists p E, E < 6 /\ n = 6 * p + E.
Proof.
  intro n. exists (n / 6), (n mod 6). split; [apply Nat.mod_upper_bound; lia |].
  apply Nat.div_mod; lia.
Qed.

