(** * Step.v : the generic cascade step on the canonical D0 moment (generated by gen/gen_step.py).

    D0f t L P s y l = 1001 (11111100)^t 11 1^L (001)^P 110 (01)^y 101 (01)^s 1 l   (Lift.v; my L = sketch L + 1).
    Every generated machine lemma SUBc_E / STOP_E / ENTRY_E / TOPENTRY / TOP1 is restated on D0f (pow splits only),
    the parked count is freed by a case split mod 6, the stop is composed with the champion clearing (CDPx, far end
    00 = the z2 gap) and the next entry, and the result is the one-g-step lemma [casc_stepP] for the reachability
    predicate [reachP Pm L] (a D0 moment at sketch value L is reached, y >= 1, parked count >= Pm + L). *)
