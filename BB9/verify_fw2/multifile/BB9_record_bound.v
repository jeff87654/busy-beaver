(** ** The exact score *)

Lemma bp_sig : { b : nat | b = iter 6 (U (12 * Bx - 11)) O }.
Proof. eexists. reflexivity. Qed.

Definition bp : nat := proj1_sig bp_sig.

Lemma bp_def : bp = iter 6 (U (12 * Bx - 11)) O.
Proof. exact (proj2_sig bp_sig). Qed.

Lemma bp_pos : 1 <= bp.
Proof. rewrite bp_def. simpl iter. apply U_pos. Qed.

Lemma Bx_split : Bx = 5 * (Bx / 5) + 1 /\ 1 <= Bx / 5.
Proof.
  pose proof Bx_mod5 as Hm. pose proof Bx_ge6 as H6.
  pose proof (Nat.div_mod Bx 5 ltac:(lia)) as Hd. rewrite Hm in Hd. clear Hm.
  remember (Bx / 5) as m eqn:Em. clear Em. lia.
Qed.

Theorem score_exact :
  exists c, c0 -->* c /\ halted tm c /\ ones c (6 * bp + 108 * (Bx / 5) + 82).
Proof.
  destruct Bx_split as [HB Hm1].
  remember (Bx / 5) as m eqn:Em. clear Em.
  pose proof bp_pos as Hb.
  exists (c_end (12 * m - 2) (3 * bp - 3)).
  split; [| split].
  - eapply evstep_trans; [apply run_to_exhaustion |].
    eapply evstep_trans; [apply (run_to_D2 Bx ltac:(lia)) |].
    rewrite <- bp_def.
    replace (12 * Bx - 11) with (5 * (12 * m - 2) + 11) by lia.
    apply d2_end. exact Hb.
  - apply c_end_halted.
  - replace (6 * bp + 108 * m + 82) with (9 * (12 * m - 2) + 2 * (3 * bp - 3) + 106) by lia.
    apply ones_c_end.
Qed.

(** ** Closed forms *)

Lemma iterU_closed : forall k n, 2 * iter n (U k) O + 4 = arrow (S (S k)) 2 (n + 2).
Proof.
  intros k n. induction n as [| n IHn].
  - change (2 * iter 0 (U k) O + 4) with 4. change (0 + 2) with 2. rewrite arrow_two. reflexivity.
  - change (iter (S n) (U k) O) with (U k (iter n (U k) O)).
    rewrite (U_closed k (iter n (U k) O)), IHn.
    replace (S n + 2) with (S (n + 2)) by lia. rewrite arrow_SS. reflexivity.
Qed.

Lemma bp_closed : 2 * bp + 4 = arrow (12 * Bx - 9) 2 8.
Proof.
  rewrite bp_def, (iterU_closed (12 * Bx - 11) 6).
  pose proof Bx_ge6. replace (S (S (12 * Bx - 11))) with (12 * Bx - 9) by lia.
  change (6 + 2) with 8. reflexivity.
Qed.

(** 2 Bx + 4 = 2 ^11 (2 ^11 4) = 2 ^13 3  (arrows; fully instantiated rewrites only) *)
Lemma Bx_arrow13 : 2 * Bx + 4 = arrow 13 2 3.
Proof.
  rewrite Bx_closed.
  rewrite (arrow_SS 12 2 2), (arrow_two 13), (arrow_SS 11 2 3), (arrow_SS 11 2 2), (arrow_two 12).
  reflexivity.
Qed.

Theorem score_closed :
  exists c, c0 -->* c /\ halted tm c /\ ones c (3 * arrow (12 * Bx - 9) 2 8 + 108 * (Bx / 5) + 70).
Proof.
  destruct score_exact as [c [H1 [H2 H3]]].
  exists c. split; [exact H1 | split; [exact H2 |]].
  rewrite <- bp_closed.
  replace (3 * (2 * bp + 4) + 108 * (Bx / 5) + 70) with (6 * bp + 108 * (Bx / 5) + 82) by lia.
  exact H3.
Qed.

(** ** Up-arrows with base 2: monotonicity (BB8_champ35_bound.v) *)

Lemma iter_add : forall a b g x, iter (a + b) g x = iter a g (iter b g x).
Proof. induction a; intros; simpl. - reflexivity. - rewrite IHa. reflexivity. Qed.

Lemma iter_ge : forall g, (forall a, a <= g a) -> forall n x, x <= iter n g x.
Proof.
  intros g Hg. induction n; intros; simpl. - lia.
  - specialize (IHn x). specialize (Hg (iter n g x)). lia.
Qed.

Lemma iter_mono_n : forall g, (forall a, a <= g a) -> forall n m x, n <= m -> iter n g x <= iter m g x.
Proof.
  intros g Hg n m x Hnm. replace m with ((m - n) + n) by lia.
  rewrite iter_add. apply iter_ge. exact Hg.
Qed.

Lemma iter_lin1 : forall g, (forall a, 1 <= a -> a + 1 <= g a) -> forall n x, 1 <= x -> x + n <= iter n g x.
Proof.
  intros g Hg. induction n; intros x Hx; simpl. - lia.
  - specialize (IHn x Hx). specialize (Hg (iter n g x) ltac:(lia)). lia.
Qed.

Lemma arrow_props : forall k,
  (forall x y, x <= y -> arrow k 2 x <= arrow k 2 y) /\ (forall x, 1 <= x -> x + 1 <= arrow k 2 x) /\
  (forall x, x <= arrow k 2 x).
Proof.
  induction k as [| k [Hm [Hs Hi]]].
  - split; [intros x y Hxy | split; [intros x Hx | intros x]];
    rewrite ?(arrow_0 2 x); rewrite ?(arrow_0 2 y); lia.
  - assert (Hm' : forall x y, x <= y -> arrow (S k) 2 x <= arrow (S k) 2 y).
    { intros x y Hxy. rewrite !arrow_S_iter. apply iter_mono_n; assumption. }
    assert (Hs' : forall x, 1 <= x -> x + 1 <= arrow (S k) 2 x).
    { intros x Hx. rewrite arrow_S_iter.
      pose proof (iter_lin1 (arrow k 2) Hs x 1 ltac:(lia)) as Hl.
      destruct x as [| x']; [lia |].
      simpl iter. pose proof (Hs (iter x' (arrow k 2) 1)).
      pose proof (iter_lin1 (arrow k 2) Hs x' 1 ltac:(lia)). lia. }
    split; [exact Hm' | split; [exact Hs' |]].
    intros x. destruct x as [| x']; [lia |]. pose proof (Hs' (S x') ltac:(lia)). lia.
Qed.

Lemma arrow_mono : forall k x y, x <= y -> arrow k 2 x <= arrow k 2 y.
Proof. intros. apply arrow_props. assumption. Qed.

Lemma arrow_gt : forall k x, 1 <= x -> x + 1 <= arrow k 2 x.
Proof. intros. apply arrow_props. assumption. Qed.

Lemma arrow_level : forall k x, arrow k 2 x <= arrow (S k) 2 x.
Proof.
  intros k x. destruct x as [| x'].
  - rewrite arrow_S0. destruct k; [rewrite (arrow_0 2 0); lia | rewrite arrow_S0; lia].
  - rewrite arrow_SS. apply arrow_mono.
    rewrite arrow_S_iter.
    pose proof (iter_lin1 (arrow k 2) (arrow_gt k) x' 1 ltac:(lia)). lia.
Qed.

Lemma arrow_level_mono : forall d k x, arrow k 2 x <= arrow (d + k) 2 x.
Proof.
  induction d; intros k x. - reflexivity.
  - specialize (IHd k x). pose proof (arrow_level (d + k) x). change (S d + k) with (S (d + k)). lia.
Qed.

(** ** Lower bounds *)

(** score > 2 ^(6T-33) 8 with T = 2 ^13 3 (arrows) *)
Theorem sigma_lower_bound_strong :
  exists c N, c0 -->* c /\ halted tm c /\ ones c N /\ arrow (6 * arrow 13 2 3 - 33) 2 8 < N.
Proof.
  destruct score_exact as [c [H1 [H2 H3]]].
  exists c, (6 * bp + 108 * (Bx / 5) + 82).
  split; [exact H1 | split; [exact H2 | split; [exact H3 |]]].
  pose proof bp_closed as E. pose proof Bx_ge6 as H6.
  rewrite <- Bx_arrow13.
  replace (6 * (2 * Bx + 4) - 33) with (12 * Bx - 9) by lia.
  rewrite <- E. generalize (Bx / 5). intros. lia.
Qed.

(** score > 2 ^(2 ^13 3) 3 (arrows) *)
Theorem sigma_lower_bound :
  exists c N, c0 -->* c /\ halted tm c /\ ones c N /\ arrow (arrow 13 2 3) 2 3 < N.
Proof.
  destruct score_exact as [c [H1 [H2 H3]]].
  exists c, (6 * bp + 108 * (Bx / 5) + 82).
  split; [exact H1 | split; [exact H2 | split; [exact H3 |]]].
  pose proof bp_closed as E. pose proof Bx_ge6 as H6.
  assert (L1 : arrow (2 * Bx + 4) 2 3 <= arrow (12 * Bx - 9) 2 3).
  { replace (12 * Bx - 9) with ((10 * Bx - 13) + (2 * Bx + 4)) by lia. apply arrow_level_mono. }
  assert (L2 : arrow (12 * Bx - 9) 2 3 <= arrow (12 * Bx - 9) 2 8) by (apply arrow_mono; lia).
  rewrite <- Bx_arrow13.
  rewrite <- E in L2.
  generalize dependent (arrow (2 * Bx + 4) 2 3). generalize dependent (arrow (12 * Bx - 9) 2 3).
  generalize (Bx / 5). intros. lia.
Qed.

