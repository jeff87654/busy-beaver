Lemma res_split : forall X : nat, ((Z.of_nat X) mod Mres = rho)%Z -> exists q : Z, (0 <= q)%Z /\ Z.of_nat X = (Mres * q + rho)%Z.
Proof.
  intros X H. exists (Z.of_nat X / Mres)%Z. split.
  - apply Z.div_pos; unfold Mres; lia.
  - rewrite <- H. apply Z.div_mod. unfold Mres. lia.
Qed.

